# Lexical normalization of an absolute path: drops `.` and empty segments and
# folds `..`. Written with parameter expansion only (no word splitting), so it
# behaves the same under bash and zsh.
nv_normalize() {
  local rest=${1#/} seg out=""
  while [ -n "$rest" ]; do
    case "$rest" in
      */*)
        seg=${rest%%/*}
        rest=${rest#*/}
        ;;
      *)
        seg=$rest
        rest=""
        ;;
    esac
    case "$seg" in
      "" | .) ;;
      ..) out=${out%/*} ;;
      *) out="$out/$seg" ;;
    esac
  done
  printf '%s' "${out:-/}"
}

# Physical form of an absolute normalized path: the nearest existing ancestor is
# resolved with `cd -P`, and the not-yet-existing tail is appended as written.
# Empty output means it could not be resolved.
nv_realdir() {
  local d=$1 suffix="" real parent
  while [ ! -e "$d" ] && [ ! -L "$d" ] && [ "$d" != "/" ]; do
    suffix="/${d##*/}$suffix"
    d=${d%/*}
    [ -n "$d" ] || d=/
  done
  if [ -d "$d" ]; then
    real=$(cd -P "$d" 2>/dev/null && pwd -P) || return 0
  else
    parent=${d%/*}
    [ -n "$parent" ] || parent=/
    real=$(cd -P "$parent" 2>/dev/null && pwd -P) || return 0
    real="${real%/}/${d##*/}"
  fi
  printf '%s' "${real%/}$suffix"
}

# Follow a leaf symlink chain (bounded) on top of `nv_realdir`.
nv_realpath() {
  local p=$1 n=0 target
  while :; do
    p=$(nv_realdir "$p")
    [ -n "$p" ] || return 0
    if [ -L "$p" ] && [ "$n" -lt 20 ]; then
      target=$(readlink "$p") || break
      case "$target" in
        /*) p=$(nv_normalize "$target") ;;
        *) p=$(nv_normalize "${p%/*}/$target") ;;
      esac
      n=$((n + 1))
    else
      break
    fi
  done
  printf '%s' "$p"
}

# 0 when the physical path sits under an OS temp root (resolved the same way, so
# `/tmp` -> `/private/tmp` and `$TMPDIR` -> `/private/var/folders/...` compare).
nv_in_temp() {
  local root real
  for root in /tmp /var/tmp "${TMPDIR:-}"; do
    [ -n "$root" ] || continue
    real=$(cd -P "$root" 2>/dev/null && pwd -P) || continue
    case "$1" in
      "${real%/}"/*) return 0 ;;
    esac
  done
  return 1
}

# Root of the nested LINKED worktree of the session repo that really contains
# the canonical path $1 (under session root $2), e.g. `.navori/state/fixtures/*`
# or `.claude/worktrees/*` (#1022). Accepted only when git reports a toplevel
# strictly under $2 that is registered in `git worktree list`, shares the
# session's --git-common-dir and is linked (its --git-dir differs from the common
# dir). Anything else (independent nested repo, other repo's worktree, forged
# `.git`) falls back to $2. $1 is canonical, so symlinks and `..` cannot move
# it into another tree. Same identity primitives as #1330's nv_sibling_rel.
nv_containing_root() {
  local d=${1%/*} top common gitdir sessioncommon list
  while [ -n "$d" ] && [ ! -d "$d" ]; do d=${d%/*}; done
  if [ -n "$d" ]; then
    top=$(git -c core.fsmonitor=false -C "$d" rev-parse --show-toplevel 2>/dev/null) &&
      top=$(cd -P "$top" 2>/dev/null && pwd -P) || top=""
    case "$top" in
      "$2"/?*)
        case "$1" in
          "$top"/?*)
            common=$(git -c core.fsmonitor=false -C "$top" rev-parse --path-format=absolute --git-common-dir 2>/dev/null) &&
              gitdir=$(git -c core.fsmonitor=false -C "$top" rev-parse --path-format=absolute --git-dir 2>/dev/null) &&
              sessioncommon=$(git -c core.fsmonitor=false -C "$2" rev-parse --path-format=absolute --git-common-dir 2>/dev/null) &&
              common=$(cd -P "$common" 2>/dev/null && pwd -P) &&
              gitdir=$(cd -P "$gitdir" 2>/dev/null && pwd -P) &&
              sessioncommon=$(cd -P "$sessioncommon" 2>/dev/null && pwd -P) &&
              [ "$common" = "$sessioncommon" ] && [ "$gitdir" != "$common" ] &&
              list=$(git -c core.fsmonitor=false -C "$2" worktree list --porcelain 2>/dev/null) &&
              printf '%s\n' "$list" | grep -Fxq "worktree $top" &&
              { printf '%s' "$top"; return 0; }
            ;;
        esac
        ;;
    esac
  fi
  printf '%s' "$2"
}

