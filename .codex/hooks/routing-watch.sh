navori_is_source() {
  [ -n "${1:-}" ] || return 1
  local _p
  # ephemeral: agent handoffs and reclaimed worktrees: never versioned, never in a diff
  _p='(^|/)\.claude/(progress|worktrees)/'; [[ $1 =~ $_p ]] && return 1
  # ephemeral: throwaway scaffolding; 13.4% of the miner's old 'source' writes were this
  _p='(^|/)(scratchpad|\.scratch)/'; [[ $1 =~ $_p ]] && return 1
  # dependency: a vendored dependency is not ours to change, and a write there is an accident
  _p='(^|/)node_modules/'; [[ $1 =~ $_p ]] && return 1
  # dependency: build output: regenerated from the source this same change may edit
  _p='(^|/)(dist|build|out|coverage|\.next|\.astro)/'; [[ $1 =~ $_p ]] && return 1
  # generated: the rendered harness mirror — the change lives in the source asset, not here
  _p='(^|/)\.claude/'; [[ $1 =~ $_p ]] && return 1
  # generated: rendered from managed blocks; editing it directly is what the drift guard blocks
  _p='(^|/)(CLAUDE|AGENTS)\.md$'; [[ $1 =~ $_p ]] && return 1
  # generated: rendered from the plugin manifests; editing it here is overwritten next render
  _p='(^|/)\.mcp\.json$'; [[ $1 =~ $_p ]] && return 1
  # generated: regenerated from the tree it pins; never hand-authored
  _p='(^|/)__golden__/|\.snap$'; [[ $1 =~ $_p ]] && return 1
  # lockfile: resolved by a tool, reviewed as a diff of intent elsewhere
  _p='(^|/)(pnpm-lock\.yaml|package-lock\.json|yarn\.lock|bun\.lockb?|Cargo\.lock|poetry\.lock|Gemfile\.lock|go\.sum)$'; [[ $1 =~ $_p ]] && return 1
  # fixture: data the tests read, not behavior the program runs
  _p='(^|/)(__fixtures__|__mocks__|fixtures)/'; [[ $1 =~ $_p ]] && return 1
  # test: clause (c): a test pinning a change counted elsewhere is evidence, not a second file
  _p='\.(test|spec)\.[mc]?[jt]sx?$'; [[ $1 =~ $_p ]] && return 1
  # test: same clause, for repos that group tests by directory instead of by suffix
  _p='(^|/)(__tests__|tests?)/'; [[ $1 =~ $_p ]] && return 1
  # test: same clause, Python and Go naming
  _p='(^|/)(test|tests)_[^/]+\.py$|(^|/)[^/]+_test\.(py|go)$'; [[ $1 =~ $_p ]] && return 1
  # config: clause (a) excludes config explicitly
  _p='(^|/)(package\.json|tsconfig[^/]*\.json|jsconfig\.json|biome\.jsonc?|\.eslintrc[^/]*|\.prettierrc[^/]*|\.editorconfig|\.gitignore|\.npmrc|\.nvmrc)$'; [[ $1 =~ $_p ]] && return 1
  # config: declares what the harness renders; the behavior it changes is navori's, not the repo's
  _p='(^|/)navori\.config\.json$'; [[ $1 =~ $_p ]] && return 1
  # docs: read by humans; no agent obeys it as instruction
  _p='(^|/)(docs|specs)/|(^|/)(README|CONTRIBUTING|CHANGELOG|LICENSE)[^/]*$'; [[ $1 =~ $_p ]] && return 1
  # docs: the session log, versioned but not behavior
  _p='(^|/)progress/'; [[ $1 =~ $_p ]] && return 1
  # Harness prose an agent obeys is behavior even though it is .md.
  _p='(^|/)(core-assets|plugins)/(.*/)?(agents|skills|managed)/[^/]+\.md$'; [[ $1 =~ $_p ]] && return 0
  _p='\.(ts|tsx|mts|cts|js|jsx|mjs|cjs|py|go|rs|java|kt|rb|php|cs|swift|sh|bash|zsh|sql|vue|svelte|astro|ipynb)$'; [[ $1 =~ $_p ]] && return 0
  return 1
}

# The candidate targets: one for a native tool, possibly several for a shell
# command that writes more than once.
if [ "$tool" = "Bash" ]; then
  # Rung 1 already ran, way up next to the tool `case`, so reaching here means
  # the payload carries a write token somewhere. Now it is worth one fork to
  # find out WHERE.
  navori_cmd=$(extract_cmd)
  [ -n "$navori_cmd" ] || exit 0
  # Rung 2: the same probe, on the COMMAND this time. Rung 1 had to read the
  # whole payload — which carries `tool_response`, i.e. the command's own
  # OUTPUT — so all it can answer is "maybe"; this answers "yes". Measured, it
  # ends a further 25% of the park's Bash calls one fork before the extraction
  # pipeline below (three more) would have found nothing (same discipline as
  # #716: the second payload read has to be earned, and so does the third).
  navori_has_write_token "$navori_cmd" || exit 0
  # The three forms `guard-destructive` rule 6 recognizes. One `grep -oE` pass,
  # because a shell-level parse of every redirect is not worth a fork per
  # operand — and this is a counter, not a gate.
  #
  # APPENDS ARE COUNTED, and this comment used to claim the opposite ("`>>` and
  # `tee -a` append, which is why neither appears here"). The pattern below has
  # no `>>` branch, but it does not need one: scanning left to right, the first
  # `>` of a `>>` fails (the next character is `>`, which the operand class
  # excludes) and the SECOND one matches, so `cat >> src/a.ts` yields
  # `src/a.ts`. Verified at the shell, not read off the regex. Counting it is
  # the right answer — appending to a source file is writing to it — so the
  # behaviour stays and the claim goes. `tee -a` genuinely does not count: its
  # operand is the flag, which the `grep -v '^-'` below drops.
  # `navori_has_write_token` depends on this being true, which is why it is
  # written down instead of inferred.
  files=$(printf '%s' "$navori_cmd" | grep -oE '(>\|?[[:space:]]*|(^|[[:space:]])tee[[:space:]]+)[^[:space:]|&;<>]+' 2>/dev/null \
    | sed -E -e 's/^[[:space:]]*//' -e 's/^>\|?[[:space:]]*//' -e 's/^tee[[:space:]]+//' -e 's/^[[:space:]]*//' \
    | grep -v '^-' || true)
  # `sed -i` names its target last, and the redirect pass above cannot see it.
  case "$navori_cmd" in
    *"sed "*-i*)
      navori_last=${navori_cmd##* }
      case "$navori_last" in
        -*) ;;
        *) files=$(printf '%s\n%s' "$files" "$navori_last") ;;
      esac
      ;;
  esac
else
  # `nv_edited_paths` already covers `tool_input.file_path`/`.notebook_path`
  # (Claude) and, under Codex's `apply_patch`, every path the patch's own
  # `*** Add/Update/Delete File:`/`Move to:` headers name — the loop below
  # already reads one path per line, so a multi-file patch is nothing new.
  files=$(nv_edited_paths)
fi
[ -n "$files" ] || exit 0

while IFS= read -r file; do
  [ -n "$file" ] || continue
  # Quotes survive the extraction above; a path is what is inside them.
  file=$(printf '%s' "$file" | tr -d "\"'")

  # Repo-relative, or not counted at all. The hook `cd`s to CLAUDE_PROJECT_DIR
  # above, so $PWD is the repo root.
  #
  # Without this the count included files that reach no diff: a scratch script
  # under /tmp, another repo's file opened in the same session. Measured on the
  # park, 13.4% of what the activation miner called "source writes" were exactly
  # that — and this hook had the same hole, so its notice could fire on a session
  # that had written nothing but scaffolding.
  case $file in
    "$PWD"/*) file=${file#"$PWD"/} ;;
    /*) continue ;;
  esac

  # And only what carries behavior. A render that rewrites 45 mirror files is not
  # a change anyone should delegate, and counting it as four was how this notice
  # could fire on a release.
  navori_is_source "$file" || continue

  mark "path:$file"
done <<NAVORI_FILES
$files
NAVORI_FILES

count=$(grep -c '^path:' "$stamp" 2>/dev/null) || count=0
[ "${count:-0}" -ge "$threshold" ] 2>/dev/null || exit 0

mark "#notified"
navori_audit_log "notify" "$count archivos del hilo principal, sin subagente"

# Written with no `"` and no `\` on purpose: that is what makes the JSON
# escaping below exact without a JSON encoder (see the awk join).
notice=$(cat <<MSG
navori: routing check. ${count} distinct files written in this session, and no subagent has been invoked.

Apply the enabled orchestration route for this repo. Do not route to an agent that this repo disabled.

If inline IS the right call here (the operator ruled delegation out, the edits are one mechanical change, the context is already paid for), say so explicitly in your next message and carry on. The point of this note is that the override stops being silent - today it leaves no trace at all.

Advisory only: nothing was blocked, and this fires at most once per session.
MSG
)

# JSON-escape by joining the lines with a literal backslash-n. Exact because the
# text above is a fixed literal free of quotes and backslashes; a payload from
# outside would need a real encoder.
escaped=$(printf '%s\n' "$notice" | awk 'NR>1 { printf "\\n" } { printf "%s", $0 }')
printf '{"hookSpecificOutput":{"hookEventName":"PostToolUse","additionalContext":"%s"}}\n' "$escaped"

# The last word of the script, and the contract of the whole file: advisory.
exit 0
