"""Harbor's Claude Code agent, extended so a variant can declare its harness.

Harbor's built-in ``claude-code`` agent already isolates ``CLAUDE_CONFIG_DIR`` per
trial, but it cannot load plugins, run a harness installer, or use ``--bare``.
This subclass adds exactly those three things and nothing else.

Usage (normally generated by ``owl run`` from a variant manifest)::

    harbor run -p tasks/00-smoke \\
      -a owl.agents.claude_code_harness:ClaudeCodeHarness \\
      --ak plugin_dirs=/abs/path/superpowers --ak variant_id=superpowers
"""

from __future__ import annotations

import shlex
from pathlib import Path, PurePosixPath

from harbor.agents.installed.claude_code import ClaudeCode, ClaudeCodeOptions
from harbor.environments.base import BaseEnvironment
from harbor.models.agent.context import AgentContext
from pydantic import Field


class ClaudeCodeHarnessOptions(ClaudeCodeOptions):
    variant_id: str | None = Field(
        default=None, description="Variant id, recorded for the contamination gate."
    )
    plugin_dirs: str | None = Field(
        default=None,
        description="Comma-separated host directories, each loaded with --plugin-dir.",
    )
    init_command: str | None = Field(
        default=None,
        description="Shell command run in /app (as the agent user) before the agent starts.",
    )
    bare: bool = Field(
        default=False,
        description="Pass --bare (skips all auto-discovery; requires ANTHROPIC_API_KEY).",
    )


class ClaudeCodeHarness(ClaudeCode):
    options_model = ClaudeCodeHarnessOptions
    options: ClaudeCodeHarnessOptions

    _REMOTE_PLUGINS_DIR = PurePosixPath("/opt/owl/plugins")

    @staticmethod
    def name() -> str:
        return "claude-code-harness"

    def _plugin_sources(self) -> list[Path]:
        raw = self.options.plugin_dirs or ""
        return [Path(p).expanduser().resolve() for p in raw.split(",") if p.strip()]

    def _remote_plugin_dir(self, source: Path) -> PurePosixPath:
        return self._REMOTE_PLUGINS_DIR / source.name

    def build_cli_flags(self) -> str:
        flags = [super().build_cli_flags()]
        if self.options.bare:
            flags.append("--bare")
        for source in self._plugin_sources():
            flags.append(f"--plugin-dir {shlex.quote(self._remote_plugin_dir(source).as_posix())}")
        return " ".join(f for f in flags if f)

    async def run(
        self, instruction: str, environment: BaseEnvironment, context: AgentContext
    ) -> None:
        for source in self._plugin_sources():
            if not (source / ".claude-plugin").is_dir():
                raise ValueError(f"Not a Claude Code plugin (no .claude-plugin/): {source}")
            await environment.upload_dir(source, self._remote_plugin_dir(source).as_posix())

        if self.options.init_command:
            await self.exec_as_agent(
                environment,
                command=f"cd /app && {self.options.init_command}",
                env=self._resolve_auth_env(),
            )

        await super().run(instruction, environment, context)
