#!/usr/bin/env bash
#
# PostToolUse watcher for managed-block drift (#530), on every tool that can
# write a file: `Bash|Edit|Write|NotebookEdit`.
#
# WHY THE MATCHER IS THE WHOLE DECISION, and why it took #775 to widen it. This
# script audits STATE, never the command, so it has no `case "$tool_name"` to
# contradict its registration — the matcher alone decides when it runs, which
# makes a narrow one indistinguishable from a hook that works. It was `Bash`
# only, and the host's own PostToolUse doc spells out the consequence from the
# other direction: a hook matching `Edit|Write` does not run when a `Bash`
# command rewrites the same file. The inverse is the hole this had — in
# `default`/`acceptEdits`, where the host does NOT push everything through the
# shell, an `Edit` over `CLAUDE.md` broke a managed block's hash and this stayed
# quiet until the next Bash call, if one ever came. A session of pure native
# editing put the #523 freeze back into silence, which is the one thing this
# hook exists to prevent.
#
# WHY NOT `FileChanged`, which the same doc section recommends for exactly this
# ("to run a hook when a specific file changes on disk, whatever wrote it").
# The CONTRACT is not the reason, and this comment used to say it was: core can
# register the event today. `lib/config/plugins.ts:91` admits four events, but that
# enum is the schema for a PLUGIN MANIFEST and is used nowhere else —
# `buildClaudeSettings` returns `Record<string, unknown>` and validates no event
# name at all, which is how core already ships `SessionEnd` and
# `UserPromptSubmit`. Only a plugin registering `FileChanged` would need the
# vocabulary widened. Three other things stop it:
#
#   1. The watchlist would live IN the settings, and the managed file set is
#      derived per repo at render time (engine outputs plus every rendered
#      asset, ~60 files here) — so settings.json would carry a second copy of a
#      list this script already derives, and the two would drift. A watchlist
#      that drifts from the managed set is a detector with holes in it, i.e.
#      this hook's own defect class.
#   2. It loses the channel to the model. `FileChanged` has no decision
#      control: the host shows its stderr "to user only", reads `watchPaths`
#      and `systemMessage` out of the JSON output and discards `continue`, and
#      that `systemMessage` is a brief terminal notification that "doesn't
#      reach the SDK message stream". Everything this hook does ends in
#      `exit 2` → stderr → the MODEL, which is what gets the freeze repaired in
#      the same turn. Migrating would downgrade the recipient of the warning.
#   3. Its matcher cannot name these paths. `FileChanged` and `StopFailure` use
#      a narrower exact-match set — letters, digits, `_` and `|` only — and
#      every root this watches (`CLAUDE.md`, `.claude/settings.json`,
#      `.claude/agents/…`) carries a dot, a slash or a hyphen, which drops the
#      matcher onto the regular-expression path. The one viable route is
#      `watchPaths` (absolute paths) returned from `SessionStart`, which is
#      more machinery and still subject to (1) and (2).
#
# What the widening does NOT buy, stated plainly: a write from outside the
# session — a formatter in a watch process, another terminal — still surfaces
# only on the next tool call navori sees. `FileChanged` would catch that one.
# The cost of what it does buy is one shasum pass (~35ms, quoted below) per
# native edit.
#
# THIS HOOK NEVER READS THE COMMAND. That is the whole design. Its sibling
# `guard-destructive.sh` decides by the SHAPE of what you typed, so it only ever
# covers the write verbs someone enumerated — `>`, `sed -i`, `tee` — and misses
# `python -c`, `perl -i`, `awk > file`, a formatter, or a script the agent
# didn't write. The blind audit found that "describe the danger by its textual
# form" pattern eight times, four of them with a test pinning the hole shut.
#
# So this one asks the only question that has no form: AFTER the command ran,
# do navori's managed blocks still hash to what their markers claim? A block
# whose body changed is a block navori will refuse to update from now on
# (`user-modified-skipped`) — the #523 freeze, arriving in silence. Whatever
# rewrote it, legitimately or not, this notices.
#
# The managed block below is regenerated by `navori render` and must NOT be
# edited by hand.
#
# SCOPE. settings.json invokes hooks as `bash "$CLAUDE_PROJECT_DIR/.claude/…"`,
# so this process starts in the MAIN repo even when the command ran inside an
# agent worktree (#454). Checking the main mirror is the right default — that is
# the copy every session shares and the one a stray write actually freezes — but
# a block broken INSIDE a worktree is not seen here. It surfaces when that branch
# is rendered or reviewed.
#
# COST, mtime seal in front of the content check (spec 0054 R23, D7). Content
# hashing stays the authority: it is exact and clock-free. But one `shasum` pass
# over ~60 files (~35ms) on EVERY tool call is most of this hook's cost, so a
# SEAL sits in front of it: `find <roots> -newer <mark>` (files AND directories,
# so a created or deleted file counts) prints nothing → nothing changed since the
# last hash pass → exit `clean` without hashing. A `find` error counts as "changed"
# (hash), never as clean. The pending mark is touched BEFORE the hash pass, so a write
# that lands while hashing is newer than the mark, but it only replaces the real mark
# AFTER the pass succeeded: a hook killed mid-hash leaves the old mark and re-checks.
#
# DECLARED LIMIT (challenge C8): a write that preserves mtime (`touch -r`,
# `cp -p`, `rsync -t`, a same-tick edit on a coarse-granularity filesystem) is
# invisible to the seal. The hook is advisory, and the first pass that does hash
# compares against the stored BASELINE (the stamp file, not the previous run's
# result), so the change shows up at the next hash pass instead of never.
#
# When the seal does not hold, the cost is one `shasum` pass (~35ms) compared
# against that baseline. Per-block hashing — the expensive part, ~3.5s for 53 blocks — runs
# ONLY for the files whose content actually changed, which in a normal session
# is none and in a bad one is one. That ~35ms is the MEDIAN of 13,692 recorded
# runs in `~/.navori/audits` (mean 43.7ms, p95 78ms); the "~25ms measured over
# 60 files" this used to quote was a single early sample and ran ~40% optimistic.
# Blocking classification (#1117):
#   - managed block with a misaligned hash: advisory — PostToolUse, exit 2 only reaches the model; there is
#     nothing to approve or undo here.
set -uo pipefail

