# 6c. The Pi arm (spec 0048 D4/D15, R2/R18) — three rules that exist only in a Pi copy, because only
#     Pi has no host permission system and runs this script from `.pi/navori/hooks/`. In a Claude or
#     Codex copy this whole block is skipped.
#
#     (i) CONTROL PLANE. `.pi/navori/**` (hook copies, the bridge's own scripts), `.pi/extensions/**`
#     (the extension that enforces all of this, and anything else Pi loads), `.pi/settings.json` and
#     `.pi/navori.json` decide whether and how the guards run, so an agent that can rewrite them can
#     switch the guards off. They are protected against every WRITE verb — `>`/`>>`/`>|`, `tee`,
#     `sed -i`, `rm`, `mv`, `cp`, `ln`, `dd`, `install`, `truncate`, `chmod`, `git checkout|restore`
#     and the like — and against INLINE interpreters (`python -c`, `node -e`, `perl -i`, `ruby -e`,
#     `php -r`) that name them. Reading them (`cat`, `ls`, `grep`) stays free. `cp`/`mv` match either
#     operand (a read-copy out of the plane is blocked too): the safe side of not parsing operands.
#     The match is on the path TEXT, case-insensitively: `./.pi/...`, `/abs/proj/.pi/...` and
#     `"$PWD"/.pi/...` all contain `.pi/<name>`. Still unhandled, by the header's seatbelt rule: a
#     `cd .pi/navori` followed by a relative write, a path assembled from variables, `sh -c` and
#     `eval`. The message names `navori render --apply` for the files Navori generates and says the
#     rest is edited by the user, outside the agent.
#
#     (ii) `pi --no-extensions` (or `-ne`) from bash starts a Pi with none of this loaded: no guard,
#     no bridge. Blocked, no route.
#
#     (iii) DENY RULES. The shared `deny` permissions, translated to token prefixes at render time
#     (`nv_pi_rules`, the same translation as `.codex/rules/navori.rules`), are compared with each
#     SEGMENT, quotes dropped and blanks squeezed: `sudo rm -rf x` and `mkfs /dev/sda` block, in
#     a compound command too. `mkfs.ext4 /dev/sda` does NOT: only the exact `mkfs` token matches
#     (same as Codex, codex-parity F9). A `*` glued to the last token was narrowed to the exact token (as in
#     Codex), so `rm -rf /` blocks and `rm -rf /tmp/x` does not — the numbered rules above catch the
#     variants.
#
#     (iv) ASK RULES (spec 0048 T11, R18). The shared `ask` permissions (`git reset --hard`,
#     `git push --force`, `rm -r`, `git branch -D`, …) use the same segments and the same prefix
#     match, but they do not block: the first one that matches is remembered in `navori_pi_ask` and
#     the exit trap answers `ask` once EVERY block rule (the numbered ones above and below, a `deny`
#     rule, the user section) has let the command through, so a block always wins over a question.
#     The Pi extension resolves the `ask`: one confirmation in the interactive parent, refusal plus
#     relay to the parent in a child or without UI.
if [ "$nv_engine" = pi ]; then
  _q="[\"']"
  pi_cp="\.pi/(navori(\.json|/[^[:space:];&|<>\"']*)?|extensions(/[^[:space:];&|<>\"']*)?|settings\.json)"
  pi_cp_end="([[:space:]\"';&|)<>]|\$)"
  pi_cp_msg="shell write to the Pi control plane (.pi/navori, .pi/extensions, .pi/settings.json, .pi/navori.json) — these files decide whether the guards run. Navori's own are regenerated by 'navori render --apply' (or 'navori sync'); any other change is for the user to make outside the agent"
  _pi_cp_segs=$(printf '%s' "$segments" | grep -iE "${pi_cp}${pi_cp_end}" || true)
  pi_cp_verbs="(^|[[:space:]\"'])(rm|rmdir|unlink|mv|cp|ln|dd|install|truncate|chmod|chown|rsync|tee|touch|mkdir)[[:space:]]"
  pi_cp_sed="(^|[[:space:]\"'])sed[[:space:]]+(-[a-zA-Z]*i[a-zA-Z]*[^[:space:]]*|--in-place)([[:space:]]|=)"
  pi_cp_git="^git[[:space:]]+(.*[[:space:]])?(checkout|restore)[[:space:]]"
  pi_cp_interp="(^|[[:space:]\"'])(python[0-9.]*|node(js)?|deno|bun|perl|ruby|php|osascript)[[:space:]]+(.*[[:space:]])?(-[a-zA-Z]*[cepir][a-zA-Z]*|--eval|--print)([[:space:]=]|\$)"
  if { [ -n "$_pi_cp_segs" ] && {
         printf '%s' "$_pi_cp_segs" | grep -qiE "${pi_cp_verbs}" \
         || printf '%s' "$_pi_cp_segs" | grep -qiE "${pi_cp_sed}" \
         || printf '%s' "$_pi_cp_segs" | grep -qiE "${pi_cp_git}" \
         || printf '%s' "$_pi_cp_segs" | grep -qiE "${pi_cp_interp}"; } ; } \
    || printf '%s' "$scan" | grep -qiE ">[>|]?[[:space:]]*${_q}?([^[:space:];&|<>]*/)?${pi_cp}${pi_cp_end}"; then
    block "$pi_cp_msg" managed-rewrite "navori render --apply"
  fi
  if printf '%s' "$segments" | grep -qE "(^|[[:space:]\"'/])pi[[:space:]]+(.*[[:space:]])?(--no-extensions|-ne)([[:space:]=]|\$)"; then
    block "pi --no-extensions starts an agent without Navori's guards (no extension, no bridge, no hooks)" unspecified
  fi
  if [ "$nv_pi_rules" != "-" ]; then
    _pr_segs=$(printf '%s' "$segments" | tr -d "'\"" | tr -s '[:blank:]' ' ')
    while IFS= read -r _seg; do
      _seg=${_seg# }
      _seg=${_seg% }
      [ -n "$_seg" ] || continue
      while IFS= read -r _rule; do
        case "$_rule" in 'deny '*) ;; *) continue ;; esac
        _pfx=${_rule#deny }
        case "$_seg" in
          "$_pfx" | "$_pfx "*)
            block "shared permission deny rule '${_pfx}' (the same rule that denies it in Claude and Codex)" unspecified
            ;;
        esac
      done <<< "$nv_pi_rules"
      [ -z "$navori_pi_ask" ] || continue
      while IFS= read -r _rule; do
        case "$_rule" in 'ask '*) ;; *) continue ;; esac
        _pfx=${_rule#ask }
        case "$_seg" in
          "$_pfx" | "$_pfx "*) navori_pi_ask=$_pfx; break ;;
        esac
      done <<< "$nv_pi_rules"
    done <<< "$_pr_segs"
  fi
fi

# 7. Whole-tree discards of work that exists only in the working tree (#1252).
#    A subagent that committed the wrong diff recovered with `git reset --hard`
#    and erased reviewed, uncommitted work: unlike every rule above, the damage
#    here depends on STATE, not on text — the same command is a harmless no-op on
#    a clean tree and an irreversible loss on a dirty one. So the verdict asks
#    the repository, and blocks only when there is something to lose.
#
#    COVERED (blocked when the target repo has what the command would destroy):
#      git reset --hard · git checkout -f · git checkout -- . / git checkout .
#      git restore <paths>   without --staged (or with --staged --worktree)
#        → destroyed = tracked changes: `git status --porcelain --untracked-files=no`
#      git clean -f…         (-fd, -fdx, --force; not -n/--dry-run)
#        → destroyed = untracked files (ignored ones too with -x/-X)
#    NOT COVERED: `git checkout <file>` of one path (the caller named exactly what
#      goes; the publisher's own prose forbids it), `git reset --soft/--mixed`
#      (history/index only, nothing in the tree is lost), `git restore --staged`,
#      `git stash` (recoverable), and the segment-level limits of the header.
#
#    TARGET. The command runs in the payload's `cwd`, moved by a `cd <dir>` in an
#    earlier segment or by `git -C <dir>`. The directory must be LITERAL: a `$VAR`,
#    a substitution, `cd -`, `--git-dir`/`--work-tree`, or a path that does not
#    exist cannot be inspected, so the rule FAILS CLOSED and blocks. Every `cd` is
#    taken to persist, including one inside a subshell that would not carry over:
#    a seatbelt does not model scopes. A directory that is not a git repo has
#    nothing to lose and is allowed.
#
#    Reads `segments` with quotes dropped (`git reset "--hard"` is `--hard`), so
#    obfuscated and compound forms reach it exactly like rules 1-3. Each candidate
#    costs a `git status`, so their number is bounded and past it the verdict is
#    `block` (#511's rule: too much to inspect is denied, never waved through).
#    CEILING: `git status` over a very large tree can itself outlast the hook's
#    timeout; trigger to revisit — an audited `ms` near the limit on this rule.
# Loose on purpose: the verb only has to be a word of a `git` segment, so a
# substitution between `git` and the verb (`git -C $(pwd) reset --hard`) still
# makes the segment a candidate; the token walk below decides the real subcommand.
_dsc_re='^git[[:space:]]+(.*[[:space:]])?(reset|checkout|restore|clean)([[:space:]]|$)'
_dsc_route="commit the work first (a WIP commit is enough: 'git add -A && git commit -m wip'), or ask the user to run the discard outside the agent."
segments_dq=$(printf '%s' "$segments" | tr -d "'\")")
_dsc_cands=$(printf '%s' "$segments_dq" | grep -E "$_dsc_re" || true)
if [ -n "$_dsc_cands" ]; then
  if [ "$(printf '%s\n' "$_dsc_cands" | wc -l)" -gt 16 ]; then
    block "too many discard commands to inspect (> 16) — nothing in it was evaluated" oversize "split it into smaller commands the guard can inspect."
  fi
  # $1 dir · $2 tracked|untracked|all — succeeds when the dir holds what would be lost.
  _dsc_dirty() {
    git -C "$1" rev-parse --git-dir >/dev/null 2>&1 || return 1
    case "$2" in
      tracked) [ -n "$(GIT_OPTIONAL_LOCKS=0 git -C "$1" status --porcelain --untracked-files=no 2>/dev/null)" ] ;;
      untracked) [ -n "$(git -C "$1" ls-files --others --exclude-standard 2>/dev/null | head -n 1)" ] ;;
      *) [ -n "$(git -C "$1" ls-files --others 2>/dev/null | head -n 1)" ] ;;
    esac
  }
  # $1 base dir · $2 operand → the directory it names, or `?` when it is not literal.
  _dsc_resolve() {
    case "$2" in
      '' | '~' | '~/'*) set -- "$1" "${HOME:-?}${2#\~}" ;;
    esac
    case "$1$2" in
      *'$'* | *'`'* | *'*'* | *'?'*) printf '?' ;;
      *) case "$2" in /*) printf '%s' "$2" ;; *) printf '%s/%s' "$1" "$2" ;; esac ;;
    esac
  }
  _dsc_home=$(payload_field cwd 2>/dev/null || true)
  [ -n "$_dsc_home" ] || _dsc_home=$PWD
  _dsc_cur=$_dsc_home
  while IFS= read -r _seg; do
    case "$_seg" in
      'cd' | 'cd '*)
        _dsc_arg=${_seg#cd}
        _dsc_arg=${_dsc_arg#"${_dsc_arg%%[![:space:]]*}"}
        _dsc_arg=${_dsc_arg%"${_dsc_arg##*[![:space:]]}"}
        case "$_dsc_arg" in '-P '* | '-L '*) _dsc_arg=${_dsc_arg#-? } ;; esac
        case "$_dsc_arg" in '-' | '-'*) _dsc_cur='?' ;; *) _dsc_cur=$(_dsc_resolve "$_dsc_cur" "$_dsc_arg") ;; esac
        continue
        ;;
    esac
    printf '%s' "$_seg" | grep -qE "$_dsc_re" || continue
    _dsc_dir=$_dsc_cur
    _dsc_c=0 _dsc_sub="" _dsc_want="" _dsc_kind=""
    _dsc_hard=0 _dsc_staged=0 _dsc_wt=0 _dsc_force=0 _dsc_dry=0 _dsc_all=0 _dsc_dot=0
    while IFS= read -r _t; do
      [ -n "$_t" ] || continue
      _dsc_c=$((_dsc_c + 1))
      [ "$_dsc_c" -gt 1 ] || continue   # the `git` word itself
      if [ "$_dsc_want" = C ]; then _dsc_dir=$(_dsc_resolve "$_dsc_dir" "$_t"); _dsc_want=""; continue; fi
      if [ "$_dsc_want" = skip ]; then _dsc_want=""; continue; fi
      if [ -z "$_dsc_sub" ]; then
        case "$_t" in
          -C) _dsc_want=C ;;
          -c | --namespace) _dsc_want=skip ;;
          --git-dir | --work-tree) _dsc_dir='?'; _dsc_want=skip ;;
          --git-dir=* | --work-tree=*) _dsc_dir='?' ;;
          -*) ;;
          reset | checkout | restore | clean) _dsc_sub=$_t ;;
          *'$'* | *'`'*) _dsc_dir='?' ;;
          *) [ "$_dsc_dir" = '?' ] || _dsc_sub=$_t ;;
        esac
        continue
      fi
      case "$_t" in
        --ha | --har | --hard) _dsc_hard=1 ;;
        --staged) _dsc_staged=1 ;;
        --worktree) _dsc_wt=1 ;;
        --force) _dsc_force=1 ;;
        --dry-run) _dsc_dry=1 ;;
        --*) ;;
        -*)
          case "$_t" in *S*) _dsc_staged=1 ;; esac
          case "$_t" in *W*) _dsc_wt=1 ;; esac
          case "$_t" in *f*) _dsc_force=1 ;; esac
          case "$_t" in *n*) _dsc_dry=1 ;; esac
          case "$_t" in *x* | *X*) _dsc_all=1 ;; esac
          ;;
        . | ./ | ':/' | ':/.') _dsc_dot=1 ;;
      esac
    done <<< "$(printf '%s' "$_seg" | tr -s '[:space:]' '\n')"
    case "$_dsc_sub" in
      reset) [ "$_dsc_hard" = 1 ] && _dsc_kind=tracked ;;
      checkout) { [ "$_dsc_force" = 1 ] || [ "$_dsc_dot" = 1 ]; } && _dsc_kind=tracked ;;
      restore) { [ "$_dsc_staged" = 0 ] || [ "$_dsc_wt" = 1 ]; } && _dsc_kind=tracked ;;
      clean) { [ "$_dsc_force" = 1 ] && [ "$_dsc_dry" = 0 ]; } && { [ "$_dsc_all" = 1 ] && _dsc_kind=all || _dsc_kind=untracked; } ;;
    esac
    [ -n "$_dsc_kind" ] || continue
    _dsc_msg="git ${_dsc_sub} would discard uncommitted work"
    if [ "$_dsc_dir" = '?' ] || [ ! -d "$_dsc_dir" ]; then
      block "git ${_dsc_sub} discards work and its target directory cannot be inspected (variable, substitution, missing or unresolved path)" unspecified \
        "use a literal existing directory (cd <dir> && … or git -C <dir> …), or ${_dsc_route}"
    fi
    if _dsc_dirty "$_dsc_dir" "$_dsc_kind"; then
      block "$_dsc_msg" unspecified "$_dsc_route"
    fi
  done <<< "$segments_dq"
fi

