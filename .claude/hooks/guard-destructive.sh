navori_inert_segments

# Same list with quoted spans dropped, used ONLY by the combined-short-flag
# check, so a hyphen-word inside a commit message (`-m "add -notify option"`)
# can't trip it.
segments_unquoted=$(printf '%s' "$segments" | sed -E -e "s/'[^']*'//g" -e "s/\"[^\"]*\"//g")

# Worktree resolver and session-state ratchet (#1266), shared with
# `quality-gate-pre-commit`. Both only define functions; nothing runs until the
# commit lane below calls them.
# The landing classifier (`navori_commit_landing`, below) counts commits with the shared trigger
# detector. The guard gates commits only here, whatever the engine.
TRIGGER_RE='^git([[:space:]]+-[a-zA-Z-]+(=[^[:space:]]+)?([[:space:]]+[^-][^[:space:]]*)?)*[[:space:]]+commit([[:space:]]|$)'
TRIGGER_TOKENS='commit'
# Heredoc bodies fed to `cat` are data, not commands (#1095).
TRIGGER_STRIP_HEREDOC_BODIES=1
# Shared gate detector — inlined into each hook at render time (see the include
# directive in the source scripts + lib/render/hook-includes.ts). The caller MUST set
# $TRIGGER_RE (an ERE) before the include; it decides which git ops this hook
# gates. Single source of truth for the FIX B/C wrapper-peeling logic; DO NOT
# copy this body into a hook by hand.
#
# Detect whether $1 (a possibly-compound command) invokes a gated operation.
# Splits $1 on the shell separators && || ; | and newlines, strips leading
# whitespace plus wrapper words (`(`, `\`, `command `) and `VAR=value` env
# prefixes from each segment, and returns 0 if ANY segment STARTS with a gated
# `git …` invocation on a word boundary (matched by $TRIGGER_RE). Replaces
# literal-prefix `case` matching, which silently skipped the gate for
# `cd x && git commit`, `echo y; git push`, or a leading space (#88: NEVER skip
# the gate silently). Matching a segment START means a quoted `echo "git commit"`
# does NOT trigger it. Known limitation: it cannot see through `sh -c`, `eval`,
# or obfuscation — a seatbelt, not a sandbox.
#
# Heredoc bodies (#1095): when the caller sets TRIGGER_STRIP_HEREDOC_BODIES=1,
# the body of a `cat <<TAG … TAG` heredoc is DATA, not commands, so a
# `git commit` line inside e.g. a `gh issue create --body "$(cat <<'EOF' …`
# no longer counts. It is an ALLOW-list on purpose: only a `cat` heredoc (bare,
# or inside `$(…)` of gh/git/echo/printf) with nothing chained after it is
# stripped; anything else — `bash <<EOF`, `while read c; do $c; done <<EOF`,
# `cat <<EOF | sh`, `python - <<EOF` — keeps its body, because a shell or
# interpreter may execute it. Opt-in because master-accept-confirm matches
# unanchored and must keep seeing bodies fed to a non-shell interpreter.
# The fast path on its own, so a caller can apply it EARLIER than the segment
# scan — before it has even paid to extract the command from the payload.
#
# Returns 0 when $1 may contain a gated operation, 1 when it provably cannot.
# The argument is the one the block below spells out: no $TRIGGER_RE can match
# without one of the caller's literal TOKENS appearing in the segment it
# matches, and every segment is a substring of the input. So the absence of
# every token is proof that no segment can match — and the same proof holds one
# level up, over the raw PAYLOAD the command was extracted from: JSON escaping
# touches `"`, `\` and control characters, never the letters of a token.
#
# Disarms when $TRIGGER_TOKENS is unset: with no tokens declared there is
# nothing to prove absent, so it answers "maybe" and the caller does the work.
# Fail-open to the SLOW path, never to a skip.
has_trigger_token() {
  [ -n "${TRIGGER_TOKENS:-}" ] || return 0
  # Token iteration goes through newline-split + `read`, NOT `for _tok in
  # $TRIGGER_TOKENS`: zsh does not word-split an unquoted expansion, so the
  # `for` form iterated ONCE with the whole list as a single token there — and
  # a token that can never match is a gate that never fires. Caught by the
  # bash×zsh differential suite.
  local _input="$1" _tok _nl=$'\n'
  local _toks="${TRIGGER_TOKENS// /$_nl}"
  while IFS= read -r _tok; do
    [ -n "$_tok" ] || continue
    case "$_input" in *"$_tok"*) return 0 ;; esac
  done <<< "$_toks"
  return 1
}

# Words that let a later part of a command re-enter git, the cwd or a shell.
# Text is reduced to alphanumeric words first, so `/usr/bin/git` and `(cd` match.
navori_mentions_shellish() {
  local t=" ${1//[!A-Za-z0-9_]/ } "
  case "$t" in
    *" git "*|*" cd "*|*" pushd "*|*" popd "*|*" sh "*|*" bash "*|*" zsh "*|*" dash "*|*" ksh "*) return 0 ;;
    *" env "*|*" eval "*|*" exec "*|*" command "*|*" builtin "*|*" source "*|*" xargs "*) return 0 ;;
  esac
  return 1
}

# Sets `navori_heredoc_stripped` to $1 minus the bodies (and terminators) of
# heredocs this hook may safely treat as data; the introducing line is KEPT, so
# `git commit -F - <<'EOF'` still triggers. Any doubt (second heredoc on the
# line, unterminated body, empty tag) leaves the text untouched: fail closed.
# All locals are declared once at the top: zsh prints a re-declared `local`.
navori_strip_heredoc_bodies() {
  local input="$1" line before rest seg pre pfirst tag after cmp="" out="" r=""
  local dash=0 inbody=0 tab=$'\t' nl=$'\n'
  navori_heredoc_stripped="$input"
  case "$input" in *'<<'*) ;; *) return 0 ;; esac
  while IFS= read -r line; do
    if [ "$inbody" = 1 ]; then
      cmp="$line"
      if [ "$dash" = 1 ]; then cmp="${cmp#"${cmp%%[!$tab]*}"}"; fi
      if [ "$cmp" = "$tag" ]; then inbody=0; fi
      continue
    fi
    out="$out$line$nl"
    case "$line" in *'<<'*) ;; *) continue ;; esac
    before="${line%%<<*}"
    rest="${line#*<<}"
    case "$rest" in '<'*) continue ;; esac                  # here-string: no body
    dash=0
    case "$rest" in -*) dash=1; rest="${rest#-}" ;; esac
    rest="${rest#"${rest%%[![:space:]]*}"}"
    tag=""; after=""
    case "$rest" in
      \'*) r="${rest#\'}"; case "$r" in *\'*) tag="${r%%\'*}"; after="${r#*\'}" ;; esac ;;
      \"*) r="${rest#\"}"; case "$r" in *\"*) tag="${r%%\"*}"; after="${r#*\"}" ;; esac ;;
      \\*) r="${rest#\\}"; tag="${r%%[!A-Za-z0-9_.-]*}"; after="${r#"$tag"}" ;;
      *) tag="${rest%%[!A-Za-z0-9_.-]*}"; after="${rest#"$tag"}" ;;
    esac
    [ -n "$tag" ] || continue
    # Nothing chained after the tag, and no second heredoc on the line.
    case "$after" in *'|'*|*';'*|*'&'*|*'<<'*) continue ;; esac
    # The word before `<<` must be `cat`. Inside `$(…)`/backticks the command
    # that receives cat's output must be a known data consumer, not an
    # interpreter (`bash -c "$(cat <<EOF`, `eval "$(cat <<EOF`).
    seg="$before"
    case "$before" in
      *'$('*) seg="${before##*\$\(}"; pre="${before%\$\(*}" ;;
      *'`'*) seg="${before##*\`}"; pre="${before%\`*}" ;;
      *) pre="" ;;
    esac
    if [ -n "$pre" ]; then
      pre="${pre##*&&}"; pre="${pre##*;}"; pre="${pre##*|}"
      pre="${pre#"${pre%%[![:space:]]*}"}"
      pfirst="${pre%%[[:space:]]*}"
      case "$pfirst" in gh|git|echo|printf) ;; *) continue ;; esac
    fi
    seg="${seg#"${seg%%[![:space:]]*}"}"
    case "$seg" in *'|'*|*';'*|*'&'*) continue ;; esac
    case "$seg" in cat|cat[[:space:]]*) ;; *) continue ;; esac
    inbody=1
  done <<< "$input"
  [ "$inbody" = 0 ] || return 0                             # unterminated: keep all
  navori_heredoc_stripped="$out"
  return 0
}

# Counts the segments of $1 that start with a gated op ($TRIGGER_RE); sets the
# global `navori_trigger_hits`. `$2` = 1 stops at the first hit (is_scan_trigger
# only needs "any"). The single home of the segment normalisation, shared with
# navori_commit_landing so the two can never disagree about what a segment is.
navori_count_triggers() {
  # Pre-expanded newline: zsh does NOT expand $'\n' in the REPLACEMENT of
  # ${var//pat/repl} (it inserts the literal characters), so an inline $'\n'
  # left compound commands unsplit there and the gate silently skipped
  # `cd x && git commit` (#391). A plain variable expands identically in
  # bash and zsh. ($'\n' in PATTERN position expands fine in both.)
  local input="$1" stop="${2:-0}" segment nl=$'\n'
  navori_trigger_hits=0
  if [ "${TRIGGER_STRIP_HEREDOC_BODIES:-}" = 1 ]; then
    case "$input" in *'<<'*) navori_strip_heredoc_bodies "$input"; input="$navori_heredoc_stripped" ;; esac
  fi
  # FIX B: join `\<newline>` continuations into a space FIRST, so a command
  # split across lines with a trailing backslash stays ONE logical segment
  # (otherwise the subcommand/flag lands in a segment not starting with git).
  input="${input//\\$'\n'/ }"
  input="${input//&&/$nl}"
  input="${input//||/$nl}"
  input="${input//;/$nl}"
  input="${input//|/$nl}"
  # `<<<` feeds the already-expanded value as data — no re-evaluation — so a
  # command that contains backticks/$() is inspected, never executed.
  while IFS= read -r segment; do
    segment="${segment#"${segment%%[![:space:]]*}"}"        # strip leading ws
    # FIX C: peel wrappers so `(git …`, `\git`, `command git …` and
    # `VAR=val git …` all reduce to a plain `git …` before matching.
    while [[ "$segment" == \(* ]]; do                       # strip leading ( runs
      segment="${segment#\(}"
      segment="${segment#"${segment%%[![:space:]]*}"}"
    done
    segment="${segment#\\}"                                 # strip a leading backslash (\git)
    while [[ "$segment" =~ ^[A-Za-z_][A-Za-z0-9_]*= ]]; do  # strip VAR=val prefixes
      case "$segment" in
        *[[:space:]]*)
          segment="${segment#*[[:space:]]}"
          segment="${segment#"${segment%%[![:space:]]*}"}"
          ;;
        *) segment=""; break ;;
      esac
    done
    if [[ "$segment" == command\ * ]]; then                 # strip a leading `command ` word
      segment="${segment#command }"
      segment="${segment#"${segment%%[![:space:]]*}"}"
    fi
    # FIX C: allow git global options between `git` and the subcommand
    # (`git -c k=v commit`, `git -C /repo push`). $TRIGGER_RE's trailing boundary
    # keeps `git commitgraph` / `git config …` from matching.
    if printf '%s' "$segment" | grep -qE "$TRIGGER_RE"; then
      navori_trigger_hits=$((navori_trigger_hits + 1))
      if [ "$stop" = 1 ]; then return 0; fi
    fi
  done <<< "$input"
  return 0
}

is_scan_trigger() {
  # ─── Fast path (spec 0016 T3.2, second pass): the segment loop pays one
  # `grep -qE` FORK per segment — and a heredoc body or a 40-step compound
  # is 40 segments, so the field cost scaled with command length (measured:
  # 2.8 ms trivial, 14.8 ms for a 199-char heredoc, 95.8 ms for 40 segments;
  # p50 across one real session's commands was 40 ms per hook, not the
  # trivial floor). No $TRIGGER_RE can match without one of the caller's
  # literal TOKENS appearing in the segment it matches — and every segment is
  # a substring of the input, transformed only by insertions (`\<NL>` → space,
  # separators → newline) and prefix-peeling, none of which can CREATE a
  # token. So a single in-process substring scan of the raw input is a strict
  # superset of the segment matches: if no token is present, no segment can
  # match, and the gate answers "not for me" without a single fork. Same
  # argument, same safe direction, as the guard's own fast path.
  #
  # $TRIGGER_TOKENS is set by the including hook NEXT TO its $TRIGGER_RE, so
  # the pair travels together; when unset the fast path disarms and the loop
  # runs exactly as before (fail-open to the SLOW path, never to a skip).
  has_trigger_token "$1" || return 1
  navori_count_triggers "$1" 1
  [ "$navori_trigger_hits" -gt 0 ]
}
# Shared worktree resolver — inlined into each gate hook at render time (see the
# include directive in the source scripts + lib/render/hook-includes.ts). Requires the
# `extract-cmd` partial to have run first ($payload and $cmd in scope).
#
# WHY (#454): settings.json invokes these hooks as
# `bash "$CLAUDE_PROJECT_DIR/.claude/hooks/quality-gate-pre-commit.sh"`, so the hook
# PROCESS starts in the MAIN repo even when the commit happens inside an agent
# worktree under `.claude/worktrees/`. The old `cd "$(git rev-parse
# --show-toplevel)"` therefore resolved the main repo — whose tree is clean — so
# `git diff --name-only main` returned 0 files and the gate exited 0. Not a false
# negative from the scanner: the scanner never ran. A `cd` to an arbitrary tree
# is exactly the bug, so nothing below ever guesses: every candidate must prove
# it is a git working tree, or the next one is tried — and the one the COMMAND
# names must additionally prove it is part of the repository being protected
# (see the same-repository constraint in `navori_worktree`).
#
# `navori_worktree` prints the absolute root of the working tree the gated git
# command will act on, or nothing when none resolves. It is a FUNCTION, not a
# top-level assignment, because `quality-gate-pre-commit` inlines this partial on
# a path that runs on EVERY Bash tool call: callers pay the git/jq probes only
# after their own trigger matched.

# First shell token of $1: a leading single/double-quoted string (so a path with
# spaces survives) or an unquoted run of non-space characters.
navori_first_token() {
  local s="$1"
  case "$s" in
    \"*) s="${s#\"}"; printf '%s' "${s%%\"*}" ;;
    \'*) s="${s#\'}"; printf '%s' "${s%%\'*}" ;;
    *) printf '%s' "${s%%[[:space:]]*}" ;;
  esac
}

# Directory named by the command itself, if any. Two shapes, both real in this
# harness: `git -C <dir> commit …` (git names its own tree) and
# `cd <dir> && git commit …` (how an agent commits into its worktree from a
# session anchored elsewhere). Prints the raw token; the caller resolves it.
#
# TODO(scope): only the FIRST segment is inspected for `cd`. A `cd` buried
# mid-chain (`pnpm build && cd sub && git commit`) falls through to the payload
# cwd, which is right whenever that `cd` stays inside the same repo. Walk the
# segments if a real command shows up where it does not.
navori_cmd_dir() {
  local text="$1" rest="" head=""
  case "$text" in
    *"git -C "*)
      rest="${text#*git -C }"
      ;;
    *)
      head="${text%%&&*}"
      head="${head#"${head%%[![:space:]]*}"}"
      case "$head" in
        "cd "*) rest="${head#cd }" ;;
      esac
      ;;
  esac
  [ -n "$rest" ] || return 1
  rest="${rest#"${rest%%[![:space:]]*}"}"
  # A token that needs the shell to expand it ($VAR, `sub`, ~, globs) is NOT
  # resolved here: guessing wrong points the scan at the wrong tree, which is
  # the very failure this partial exists to kill. Ignoring it just falls through
  # to the next candidate.
  case "$rest" in
    ""|*'$'*|*'`'*|*'*'*|*'?'*|"~"*) return 1 ;;
  esac
  navori_first_token "$rest"
}

# Absolute, symlink-resolved path of a working tree's SHARED git dir, or nothing
# when $1 is not inside a git working tree. `--git-common-dir` names the `.git`
# of the MAIN checkout, so every linked worktree of one repository — and every
# subdirectory of it — reports the SAME value, while a different repository
# reports its own and a submodule reports `<main>/.git/modules/<name>`. That
# makes it an identity test for "same repository", which `--show-toplevel` (one
# per working tree) and `--git-dir` (one per worktree) are not.
navori_repo_id() {
  local dir="$1" common=""
  common=$(git -C "$dir" rev-parse --git-common-dir 2>/dev/null) || return 1
  [ -n "$common" ] || return 1
  # `git -C <dir>` chdirs to <dir> first, so a relative answer (`.git`,
  # `../../.git`) is relative to <dir>. `pwd -P` canonicalises both sides the
  # same way, which also settles macOS's /var vs /private/var symlink.
  (cd "$dir" && cd "$common" && pwd -P) 2>/dev/null
}

# First argument that resolves to a git working tree; prints its root.
navori_first_tree() {
  local candidate toplevel
  for candidate in "$@"; do
    [ -n "$candidate" ] || continue
    [ -d "$candidate" ] || continue
    toplevel=$(git -C "$candidate" rev-parse --show-toplevel 2>/dev/null) || continue
    [ -n "$toplevel" ] || continue
    printf '%s' "$toplevel"
    return 0
  done
  return 1
}

# Hook's own path, captured HERE at the partial's top level (every consumer inlines
# it at script top level). NEVER read `$0` inside a `navori_*` function: zsh sets it
# to the function's name there (FUNCTION_ARGZERO). Used only as a string, never
# resolved. A relative path is anchored on the hook's cwd, where the shell found it.
navori_hook_path="$0"
case "$navori_hook_path" in /*) ;; *) navori_hook_path="$PWD/$navori_hook_path" ;; esac
navori_home_id=""
navori_home_done=0

# HOME repository (#1099): the repo this hook protects, as a repo id in
# `navori_home_id` (empty = unknown). Known only if ALL hold:
#   - `CLAUDE_PROJECT_DIR` is non-empty;
#   - the hook's own path is exactly `${CLAUDE_PROJECT_DIR%/}/.claude/hooks/<file>`
#     or `.../.claude/scripts/<file>` (how settings.json registers it). A bare
#     prefix is not enough: a leaked variable plus a hook of a repo NESTED under it
#     would make the outer repo "home" and skip every gate of the inner one. `.codex/`
#     never qualifies, so a Codex hook is always home-unknown;
#   - that directory resolves to a repo id.
# Any doubt means unknown, and unknown never produces `foreign` without a `cd`/`-C`
# in the command. Memoised: the callers pay the git fork once. Sets a global (no
# subshell); declares locals once at the top (zsh prints a re-declared `local`).
navori_home_resolve() {
  local cpd rest file
  [ "$navori_home_done" = 0 ] || return 0
  navori_home_done=1
  cpd="${CLAUDE_PROJECT_DIR:-}"
  [ -n "$cpd" ] || return 0
  cpd="${cpd%/}"
  case "$navori_hook_path" in
    "$cpd"/*) rest="${navori_hook_path#"$cpd"/}" ;;
    *) return 0 ;;
  esac
  case "$rest" in
    .claude/hooks/*|.claude/scripts/*) file="${rest#.claude/*/}" ;;
    *) return 0 ;;
  esac
  case "$file" in ""|.|..|*/*) return 0 ;; esac
  navori_home_id=$(navori_repo_id "$CLAUDE_PROJECT_DIR" || true)
  return 0
}

# Resolution, most specific first:
#   1. the directory the command names (`git -C` / a leading `cd`), ONLY when it
#      belongs to the same repository as the anchor (see the constraint below);
#   2. the payload's `.cwd` — Claude Code sends the CURRENT working directory of
#      the tool call, a documented field distinct from $CLAUDE_PROJECT_DIR (the
#      project root). In an agent worktree these differ; that gap IS #454;
#   3. the hook process's own cwd — the pre-#454 behaviour, still correct for a
#      plain terminal or git-hook invocation.
navori_worktree() {
  local payload_cwd anchor named anchor_repo="" named_repo=""
  payload_cwd=$(payload_field cwd)
  # A relative `cd sub` resolves against the shell's cwd, which is the payload's
  # when Claude Code sends one and the hook process's otherwise.
  anchor="$payload_cwd"
  [ -d "$anchor" ] || anchor="$PWD"
  named=$(navori_cmd_dir "$cmd" || true)
  case "$named" in
    "") ;;
    /*) ;;
    *) named="$anchor/$named" ;;
  esac
  # SAME-REPOSITORY CONSTRAINT — DO NOT REMOVE (#454, review finding).
  # Candidate 1 is the only one the COMMAND controls, and it is tried first, so
  # accepting any git tree it happens to name lets that command OVERRIDE the
  # trustworthy candidates below it: `git -C <other-repo> log && git commit`,
  # `cd <other> && cd <wt> && git commit`, `cd <sub> && cd .. && git commit`, or
  # merely the bytes `git -C <path>` inside a commit MESSAGE, all aimed the scan
  # at a foreign tree with nothing to scan — exit 0 with the scanner never run,
  # which is the very failure #454 is about (and, for a commit in the main repo,
  # strictly worse than not resolving worktrees at all).
  # So a directory the command names is accepted only when it is part of the
  # repository the hook is protecting, i.e. the anchor's. Linked worktrees share
  # the main checkout's git dir, so every legitimate agent worktree passes; a
  # different repository and a submodule (its own git dir under
  # `<main>/.git/modules/`) do not, and fall through to the payload cwd — the
  # stricter direction. An unresolvable anchor drops candidate 1 for the same
  # reason: nothing to check it against — unless the named dir IS the hook's home
  # repo (#1099: the session sits in another repo but the command names the
  # protected one), which only ever moves the scan toward the protected repo.
  # Ceiling: two linked worktrees of the SAME repository are indistinguishable
  # this way, so naming a sibling worktree still beats the payload cwd. Both are
  # trees of the repo being protected, so the scan stays inside it. Walk the
  # segments to the one that actually carries the `git commit` if a real command
  # shows up where that is not enough.
  if [ -n "$named" ]; then
    anchor_repo=$(navori_repo_id "$anchor" || true)
    named_repo=$(navori_repo_id "$named" || true)
    navori_home_resolve
    if [ -z "$named_repo" ] || { [ "$named_repo" != "$anchor_repo" ] && [ "$named_repo" != "$navori_home_id" ]; }; then
      named=""
    fi
  fi
  navori_first_tree "$named" "$payload_cwd" "$PWD" || true
}

# ─── Where does the commit LAND? (#1095) ────────────────────────────────────────
# `navori_worktree` above answers "which tree do I scan"; this answers "is the
# commit even for the repository this gate protects". A commit that provably
# lands in ANOTHER repository (`cd <other> && git commit`, `git -C <other>
# commit`) must not be gated against the anchor's tree: that tree holds none of
# the diff. Classification is a POSITIVE grammar with a deny-list of ambiguity —
# `foreign` only when every step to the commit has a certain cwd effect and the
# resolved repository really differs; the commit message is never read (#454:
# `git commit -m "use git -C <other>"` lands in the anchor). Anything unsure is
# `ambiguous`, which callers treat exactly like `same-repo`: run the gate.
#
# Requires the `gate-trigger` partial (navori_count_triggers, $TRIGGER_RE) and
# `extract-cmd` (payload_field). Always returns 0 and sets, without a subshell:
#   navori_landing       same-repo | foreign | ambiguous
#   navori_landing_root  landing toplevel (foreign only)
# "foreign" means the command's landing repo differs from the repository this hook
# protects (#1099). With no `cd`/`-C` the landing dir IS the payload cwd, so a
# session anchored in another repo is foreign too. The protected repo is the HOME
# id (`navori_home_resolve`); when home is unknown the comparison degrades to the
# #1095 rule (payload-cwd repo, widened by the raw `CLAUDE_PROJECT_DIR` repo, which
# can only turn `foreign` into `same-repo`) and a command without `cd`/`-C` is
# `same-repo` with no fork. "commit" below means the one gated op.
#
# The gated op (#1098) is whatever the caller's $TRIGGER_RE counts: `git commit`
# for QG; a gate that also counts `git push` and `gh pr create` sets its own
# regex. The walk
# matches that same regex, so there is no second copy to drift. `gh pr create`
# lands in the cwd's repo unless it names another one (`-R`/`--repo`/`GH_REPO`),
# which is `ambiguous` (the scan runs).
#
# A chain of gated ops joined by `&&` (#1115) is classified per op, each with its
# own `-C` (and the one leading `cd`): `foreign` only when EVERY op lands in the
# same foreign toplevel and the walk saw every op the counter did (a hidden op
# behind `;`, `|`, `||` or a wrapper makes hits > found). One op in the home repo,
# two toplevels (even two worktrees of one repo) or an unproven op is `ambiguous`.
# After the first gated op only read-only `git` segments (status|diff|log|show|
# rev-parse|push, no global options) and echo|printf|true|:|ls|pwd may follow: the
# counter cannot see a `-C "dir with spaces"` value, an alias or an exec-capable
# subcommand, so any other tail (an `export GIT_DIR`, a later `cd`, a shell) is
# `ambiguous`. QG does not gate `push`, so `commit(F) && git push` is foreign;
# a gate whose regex counts both ops decides on both.

# Reads one shell token off the front of $1 into `navori_tok` / `navori_rest`.
# Returns 1 for anything the shell would expand or that is malformed, so the
# caller falls back to `ambiguous`.
navori_take_token() {
  local s="$1" nl=$'\n'
  navori_tok=""; navori_rest=""
  s="${s#"${s%%[![:space:]]*}"}"
  case "$s" in
    \'*)
      s="${s#\'}"
      case "$s" in *\'*) ;; *) return 1 ;; esac
      navori_tok="${s%%\'*}"; navori_rest="${s#*\'}"
      case "$navori_rest" in ""|[[:space:]]*) ;; *) return 1 ;; esac
      ;;
    \"*)
      s="${s#\"}"
      case "$s" in *\"*) ;; *) return 1 ;; esac
      navori_tok="${s%%\"*}"; navori_rest="${s#*\"}"
      case "$navori_rest" in ""|[[:space:]]*) ;; *) return 1 ;; esac
      ;;
    *)
      navori_tok="${s%%[[:space:]]*}"; navori_rest="${s#"$navori_tok"}"
      case "$navori_tok" in
        *';'*|*'|'*|*'&'*|*'<'*|*'>'*|*'('*|*')'*|*"'"*|*'"'*) return 1 ;;
      esac
      ;;
  esac
  case "$navori_tok" in
    ""|'~'*|*'$'*|*'`'*|*'\'*|*'*'*|*'?'*|*'['*|*'{'*|*"$nl"*) return 1 ;;
  esac
  return 0
}

# Where does ONE gated op land? Takes the op's `cd` target and `-C` target (either
# may be empty) and sets, without a subshell:
#   navori_op_kind  same | foreign | "" (unproven)
#   navori_op_top   landing toplevel (foreign only)
# Every unproven path returns with the empty kind.
navori_op_landing() {
  local cd_dir="$1" c_dir="$2" pcwd base dir rel=0 top sub id_l id_a id_h nl=$'\n'
  navori_op_kind=""; navori_op_top=""

  # No cd/-C: the landing dir is the payload cwd. Without a PROVEN home there is
  # nothing to compare it with, so today's answer (and zero forks) stands.
  if [ -z "$cd_dir" ] && [ -z "$c_dir" ]; then
    navori_home_resolve
    if [ -z "$navori_home_id" ]; then navori_op_kind="same"; return 0; fi
  else
    navori_home_resolve
  fi

  pcwd=$(payload_field cwd)
  base="$pcwd"
  [ -d "$base" ] || base="$PWD"
  dir="$base"
  if [ -n "$cd_dir" ]; then
    case "$cd_dir" in
      /*) dir="$cd_dir" ;;
      *)
        rel=1; dir="$base/$cd_dir"
        # A non-empty CDPATH can make `cd <relative>` land somewhere else.
        [ -z "${CDPATH:-}" ] || return 0
        ;;
    esac
  fi
  if [ -n "$c_dir" ]; then
    case "$c_dir" in
      /*) dir="$c_dir"; rel=0 ;;
      *) rel=1; dir="$dir/$c_dir" ;;
    esac
  fi
  # `..` in a relative path resolves logically in the shell but physically in
  # the kernel; they differ when the base itself sits behind a symlink.
  if [ "$rel" = 1 ]; then
    case "$cd_dir$nl$c_dir" in
      *'..'*) [ "$(cd "$base" 2>/dev/null && pwd -P)" = "$base" ] || return 0 ;;
    esac
  fi

  [ -d "$dir" ] || return 0
  top=$(git -C "$dir" rev-parse --show-toplevel 2>/dev/null) || return 0
  [ -n "$top" ] || return 0
  # A submodule target (or cwd) is deliberately not `foreign` (its commit is part
  # of the superproject's work): the anchor's gate runs.
  sub=$(git -C "$dir" rev-parse --show-superproject-working-tree 2>/dev/null) || return 0
  [ -z "$sub" ] || return 0
  id_l=$(navori_repo_id "$dir" || true)
  [ -n "$id_l" ] || return 0
  if [ -n "$navori_home_id" ]; then
    # Proven home: the one definition of foreign.
    if [ "$id_l" = "$navori_home_id" ]; then
      navori_op_kind="same"
    else
      navori_op_kind="foreign"; navori_op_top="$top"
    fi
    return 0
  fi
  # Home unknown: the #1095 rule.
  id_a=$(navori_repo_id "$base" || true)
  [ -n "$id_a" ] || return 0
  id_h=""
  if [ -n "${CLAUDE_PROJECT_DIR:-}" ]; then
    id_h=$(navori_repo_id "$CLAUDE_PROJECT_DIR" || true)
  fi
  if [ "$id_l" = "$id_a" ] || { [ -n "$id_h" ] && [ "$id_l" = "$id_h" ]; }; then
    navori_op_kind="same"
  else
    navori_op_kind="foreign"; navori_op_top="$top"
  fi
  return 0
}

# Parses the target of ONE gated segment ($1 = its first line, $2 = the whole
# segment) and sets `navori_op_cdir` to the op's `-C` target ("" when none).
# Returns 1 for anything the parser will not follow.
navori_op_target() {
  local first="$1" seg="$2" p arg nc=0
  navori_op_cdir=""
  case "$first" in
  gh[[:space:]]*)
    # `gh pr create`: no global -C, so it lands where the cwd (or the `cd`) is —
    # unless it names another repo, which the parser will not follow. Any `-R` or
    # `--repo` anywhere in the segment (message text included) reads as ambiguous.
    p="${first#gh}"
    navori_take_token "$p" || return 1
    [ "$navori_tok" = pr ] || return 1
    navori_take_token "$navori_rest" || return 1
    [ "$navori_tok" = create ] || return 1
    case "$seg" in *'-R'*|*'--repo'*) return 1 ;; esac
    [ -z "${GH_REPO:-}" ] || return 1
    return 0
    ;;
  esac
  # The segment's own git global options, positionally. Text after `commit`/
  # `push` (the message) is never read.
  p="${first#git}"
  while :; do
    navori_take_token "$p" || return 1
    arg="$navori_tok"; p="$navori_rest"
    case "$arg" in
      commit|push) return 0 ;;
      -C)
        [ "$nc" = 0 ] || return 1
        nc=1
        navori_take_token "$p" || return 1
        navori_op_cdir="$navori_tok"; p="$navori_rest"
        ;;
      -c) navori_take_token "$p" || return 1; p="$navori_rest" ;;
      --no-pager|-p|--paginate|-P|--no-optional-locks|--literal-pathspecs|--glob-pathspecs|--noglob-pathspecs|--icase-pathspecs|--no-replace-objects) ;;
      *) return 1 ;;
    esac
  done
}

navori_commit_landing() {
  local c rest seg first tailtxt gated w sub line ops="" acc="" acc_top="" prev_c="" n_done=0
  local cd_dir="" found=0 more=1 cdcount=0 nl=$'\n' tab=$'\t'
  navori_landing="ambiguous"; navori_landing_root=""

  navori_count_triggers "$1" 0
  [ "$navori_trigger_hits" -ge 1 ] || return 0

  navori_strip_heredoc_bodies "$1"
  c="$navori_heredoc_stripped"
  c="${c//\\$'\n'/ }"
  # The heredoc strip leaves a trailing newline on the last segment.
  c="${c%"${c##*[![:space:]]}"}"

  # Phase 1 — walk the `&&` chain without forking git. Before the first gated op:
  # at most one `cd <literal>` and neutral `git …` segments. Each gated op is
  # recorded with its own `-C`. After it, only a fixed allowlist of segments that
  # can neither move the cwd or env nor commit; anything else is ambiguous.
  rest="$c"
  while [ "$more" = 1 ]; do
    case "$rest" in
      *'&&'*) seg="${rest%%&&*}"; rest="${rest#*&&}" ;;
      *) seg="$rest"; rest=""; more=0 ;;
    esac
    seg="${seg#"${seg%%[![:space:]]*}"}"
    first="${seg%%"$nl"*}"
    gated=0
    case "$first" in
      git[[:space:]]*|gh[[:space:]]*)
        if printf '%s' "$first" | grep -qE "$TRIGGER_RE"; then gated=1; fi
        ;;
    esac
    if [ "$gated" = 1 ]; then
      navori_op_target "$first" "$seg" || return 0
      ops="${ops}o${navori_op_cdir}${nl}"
      found=$((found + 1))
      # Anything on this op's own line after `;`/`|`/`&`, or on later lines, could
      # re-enter git, cd or a shell (a second, uncounted commit landing elsewhere).
      tailtxt="${seg#"$first"}$nl"
      case "$first" in *';'*|*'|'*|*'&'*) tailtxt="${first#*[;|&]}$nl$tailtxt" ;; esac
      if navori_mentions_shellish "$tailtxt"; then return 0; fi
      continue
    fi
    case "$seg" in *"$nl"*) return 0 ;; esac
    seg="${seg%"${seg##*[![:space:]]}"}"
    if [ "$found" = 0 ]; then
      case "$seg" in
        cd[[:space:]]*)
          [ "$cdcount" = 0 ] || return 0
          cdcount=1
          navori_take_token "${seg#cd}" || return 0
          case "$navori_rest" in *[![:space:]]*) return 0 ;; esac
          cd_dir="$navori_tok"
          case "$cd_dir" in -*) return 0 ;; esac
          ;;
        git[[:space:]]*)
          case "$seg" in
            *';'*|*'|'*|*'&'*|*'<'*|*'>'*|*'('*|*')'*|*'$'*|*'`'*) return 0 ;;
          esac
          ;;
        *) return 0 ;;
      esac
      continue
    fi
    # After a gated op. No metacharacter, expansion or escape in any tail segment.
    case "$seg" in
      *';'*|*'|'*|*'&'*|*'<'*|*'>'*|*'('*|*')'*|*'$'*|*'`'*|*'\'*|*"$tab"*) return 0 ;;
    esac
    case "$seg" in
      git\ *)
        # Read-only subcommands, single spaces, no global options (`-C`, `-c`,
        # `--git-dir` …): an alias, an exec-capable subcommand or another repo
        # target is invisible to the counter, so it is ambiguous.
        case "$seg" in *'--exec'*|*'--receive-pack'*|*'--upload-pack'*|*'--config-env'*) return 0 ;; esac
        sub="${seg#git }"; sub="${sub%% *}"
        case "$sub" in status|diff|log|show|rev-parse|push) ;; *) return 0 ;; esac
        ;;
      *)
        w="${seg%%[[:space:]]*}"
        case "$w" in echo|printf|true|:|ls|pwd) ;; *) return 0 ;; esac
        ;;
    esac
  done
  # Every gated op the counter saw must be an op the walk parsed (INV: a hidden
  # op behind `;`, `|`, `||`, a subshell or a wrapper makes hits > found).
  [ "$found" -ge 1 ] || return 0
  [ "$found" = "$navori_trigger_hits" ] || return 0

  # Phase 2 — resolve each op with its own `-C` and fold unanimously: `foreign`
  # only when every op lands in the SAME foreign toplevel; any op in the home
  # repo, in a different toplevel or unproven leaves the verdict ambiguous.
  while IFS= read -r line; do
    case "$line" in o*) ;; *) continue ;; esac
    if [ "$n_done" = 0 ] || [ "${line#o}" != "$prev_c" ]; then
      navori_op_landing "$cd_dir" "${line#o}"
      prev_c="${line#o}"; n_done=1
    fi
    case "$navori_op_kind" in
      same) [ "$acc" != foreign ] || return 0; acc="same" ;;
      foreign)
        [ "$acc" != same ] || return 0
        if [ "$acc" = foreign ] && [ "$navori_op_top" != "$acc_top" ]; then return 0; fi
        acc="foreign"; acc_top="$navori_op_top"
        ;;
      *) return 0 ;;
    esac
  done <<< "$ops"
  case "$acc" in
    same) navori_landing="same-repo" ;;
    foreign) navori_landing="foreign"; navori_landing_root="$acc_top" ;;
  esac
  return 0
}
# Session-state ratchet (#1263, #1266) — inlined into each hook that enforces it at
# render time (see the include directive in the source scripts +
# lib/render/hook-includes.ts), and sourced as-is by the repo's own git pre-commit.
# Two consumers, ONE body: `quality-gate-pre-commit` (qualityGate.fast declared)
# and `guard-destructive` (qualityGate.fast absent), so the check never has a
# second copy to drift.
#
# The session-state file is meant to hold the CURRENT state and the next step;
# past the delivery budget it falls out of startup context. RATCHET, not a plain
# cap: blocks only when the file is over the ceiling AND larger than at HEAD, so a
# trim that is still big passes and an untouched legacy file never blocks an
# unrelated commit. The size is the max of the index (what a plain `git commit`
# lands) and the worktree (what `-a`, a pathspec or `add && commit` in one call
# lands). Bytes via `wc -c` / `git cat-file -s`: locale-independent, unlike
# `${#var}`. Every git call is guarded: an unborn HEAD or an unmerged index exits
# non-zero under `set -e`.
#
# Requires: `$navori_progress_hard_cap` (digits) set by the caller. Never exits: a
# block is `return 2`, so each host decides how to stop (and how to record it).
# Plain functions, quoted expansions, no word-splitting: they run under bash and zsh.

# Ratchet check for ONE session-state path. Returns 0 (ok) or 2 (blocked).
navori_progress_ratchet() {
  navori_pr_path=$1
  # A gitignored file is never committed, so its size is not this gate's business.
  if git check-ignore -q -- "$navori_pr_path" 2>/dev/null; then return 0; fi
  navori_pr_wt=0
  navori_pr_idx=0
  navori_pr_head=0
  if [ -f "$navori_pr_path" ]; then
    navori_pr_wt=$(wc -c <"$navori_pr_path" 2>/dev/null | tr -d '[:space:]') || navori_pr_wt=0
  fi
  navori_pr_idx=$(git cat-file -s ":$navori_pr_path" 2>/dev/null) || navori_pr_idx=0
  navori_pr_head=$(git cat-file -s "HEAD:$navori_pr_path" 2>/dev/null) || navori_pr_head=0
  case "$navori_pr_wt" in ''|*[!0-9]*) navori_pr_wt=0 ;; esac
  case "$navori_pr_idx" in ''|*[!0-9]*) navori_pr_idx=0 ;; esac
  case "$navori_pr_head" in ''|*[!0-9]*) navori_pr_head=0 ;; esac
  navori_pr_size=$navori_pr_wt
  if [ "$navori_pr_idx" -gt "$navori_pr_size" ]; then navori_pr_size=$navori_pr_idx; fi
  if [ "$navori_pr_size" -gt "$navori_progress_hard_cap" ] && [ "$navori_pr_size" -gt "$navori_pr_head" ]; then
    navori_audit_block_reason="el estado de sesion '$navori_pr_path' crecio a $navori_pr_size bytes, sobre el techo de $navori_progress_hard_cap; commit bloqueado"
    echo "[navori] Commit BLOCKED: $navori_pr_path is $navori_pr_size bytes, over the $navori_progress_hard_cap-byte ceiling, and larger than at HEAD ($navori_pr_head bytes)." >&2
    echo "[navori] It must hold only the current state and the next step. Trim it (move older checkpoints to progress/history.md) and commit again." >&2
    return 2
  fi
  return 0
}

# The whole lane for the hooks: the ceiling plus the loop over the session-state
# paths, run from the root of the tree being committed. Returns 0 or 2.
# The ceiling is injected from the single TS constant (a raw, unrendered copy
# leaves the placeholder text, which is not numeric: the lane then stays off
# rather than guess a number).
# Guarded by `-n "$cmd"`: with an empty `$cmd` (#511) the lane would run on EVERY
# Bash call and block the very command that fixes the file.
navori_progress_ratchet_lane() {
  navori_progress_hard_cap=8000
  case "$navori_progress_hard_cap" in ''|*[!0-9]*) navori_progress_hard_cap="" ;; esac
  if [ -n "$cmd" ] && [ -n "$navori_progress_hard_cap" ]; then
    for navori_pf in "progress/current.md" ".claude/progress/current.md" ".codex/progress/current.md"; do
      navori_progress_ratchet "$navori_pf" || return 2
    done
  fi
  return 0
}

# Git commit/push detector shared by rule 1. The leading boundary accepts ; & |
# so `true;git commit …` (no space after the separator) is caught; the
# `git(… -opt …)*` middle allows git global options between `git` and the
# subcommand (`git -c k=v commit …`).
git_cp='(^|[[:space:]]|[;&|])git([[:space:]]+-[a-zA-Z-]+(=[^[:space:]]+)?([[:space:]]+[^-][^[:space:]]*)?)*[[:space:]]+(commit|push)'

# 1. Skipping quality gates / hooks — defeats the whole point of the harness.
#    Two checks: the literal `--no-verify` over `segments` (quotes kept, so a
#    quoted flag is still caught), and `-[a-zA-Z]*n[a-zA-Z]*` over
#    `segments_unquoted` to catch `-n` folded into a combined short-flag token
#    (`git commit -qn`/`-nq`) without a hyphen-word in a message tripping it.
#    Both run over the SEGMENT list, so the `.*` between the git invocation and
#    the flag can never leave the segment that holds the commit/push. Matching
#    the whole command string instead is what made `git commit -m x && git log
#    -n 3` (or `&& grep -rn TODO src/`) block as a bogus "--no-verify": any short
#    flag carrying an `n` ANYWHERE later in the line was read as the commit's.
if printf '%s' "$segments"            | grep -qE "${git_cp}.*--no-verify" \
  || printf '%s' "$segments_unquoted" | grep -qE "${git_cp}.*[[:space:]]-[a-zA-Z]*n[a-zA-Z]*([[:space:]]|\$)"; then
  block "git commit/push with --no-verify (skipping hooks/gates)" no-verify "commit without --no-verify and fix what the hook reports."
fi

# 1b. Session-state ceiling on a commit when no quality-gate hook enforces it (#1266).
#     The ratchet (#1263) lives in `quality-gate-pre-commit`, which is registered
#     only with `qualityGate.fast`; without it nothing measured the file. This lane
#     runs the SAME shared body, and only when the render says `fast` is NOT
#     declared (otherwise the gate hook already measures, and doing it twice is
#     waste). The flag is injected at render time: a raw, unrendered copy keeps the
#     placeholder text, which is not `1`, so the lane stays off (fail safe, like the
#     ceiling itself). Cheap by construction: it evaluates only for a `git commit`
#     segment, and `$cmd` is non-empty here (the empty-command exit above, #511).
#     The tree measured is the one being committed (`navori_worktree`, #454); the
#     detector's limits (sh -c, eval, GIT_DIR, a `cd` mid-chain) are inherited, and
#     the repo's own git pre-commit covers the commits that bypass the agent.
#     The lane runs in a subshell so its `cd` never leaks into the rules below.
navori_pg_lane=0
if [ "$navori_pg_lane" = 1 ] \
  && printf '%s' "$segments" | grep -qE "${git_cp%\(commit\|push\)}commit([[:space:]]|\$)"; then
  # A commit that provably lands in ANOTHER repository (#1095) is not this repo's business: its
  # session-state file is not in the diff. Same rule as the gate hook: only `foreign` skips;
  # `ambiguous` and `same-repo` measure (fail closed).
  navori_commit_landing "$cmd"
  navori_pg_root=""
  if [ "$navori_landing" != foreign ]; then navori_pg_root=$(navori_worktree); fi
  if [ "$navori_landing" != foreign ] && ! ( cd "${navori_pg_root:-${nv_project_dir:-.}}" && navori_progress_ratchet_lane ); then
    # The lane already printed the verdict text; only the recording is left, and it
    # happens in the EXIT trap.
    navori_audit_verdict="block"
    navori_audit_reason="unspecified"
    exit 2
  fi
fi

# 2. Force-push to the base branch. force-with-lease is allowed (safe rebase
#    flow on feature branches); bare --force/-f against the base branch is not.
#    #307: every sub-check is scoped to the ACTUAL `git push` invocation(s),
#    never the whole command string. Keeping only the segments that START a
#    `git … push` means a `+`
#    in a commit message (`-m "format:check + test"`), a base-branch name in a
#    sibling command (`gh pr create --base main`), or a heredoc/`--body` can no
#    longer be misread as a force-push refspec or as the pushed ref — that
#    false positive blocked legit compound commit+push+PR commands. The refspec
#    `+` is matched only when glued to a ref (`+main`, never `+ test`), the way
#    git actually spells a force-push refspec.
push_seg=$(printf '%s' "$segments" \
  | grep -E '^git([[:space:]]+-[a-zA-Z-]+(=[^[:space:]]+)?([[:space:]]+[^-][^[:space:]]*)?)*[[:space:]]+push([[:space:]]|$)' \
  || true)

if [ -n "$push_seg" ] \
  && printf '%s' "$push_seg" | grep -qE '(--force([[:space:]]|$)|[[:space:]]-f([[:space:]]|$)|[[:space:]]\+[^[:space:]])' \
  && ! printf '%s' "$push_seg" | grep -qE 'force-with-lease' \
  && printf '%s' "$push_seg" | grep -qE "(^|[[:space:]+/])${base}([[:space:]]|\$)"; then
  block "force-push to the base branch '${base}'" force-push-base "push a feature branch, or use --force-with-lease on it."
fi

# 3. rm -rf with variable indirection or absolute home/system roots that static
#    deny globs miss. The deny rules in settings.json (`Bash(rm -rf ~/*)`,
#    `Bash(rm -rf /*)`) only match a command that STARTS that way, so anything
#    compound (`cd /tmp && rm -rf ~/`) walks past them — exactly the class this
#    guard exists to cover. Matching per SEGMENT is what makes that work: `$`
#    below means "end of this segment", so the target no longer has to sit at
#    the end of the whole command line.
#
#    COVERED (blocked). The FLAGS axis is normalized (see below), so every
#    spelling of "recursive/force" counts: `-rf`, `-fr`, `-r`, `-R`, `-fR`,
#    `--recursive`, `--force`, and any mix of them, with other option tokens
#    (`--no-preserve-root`, `--one-file-system`, a `--` separator) interleaved.
#    The OPERAND axis is scanned whole (see below): `rm` takes a LIST of paths,
#    so a sensitive one blocks wherever it sits in that list.
#    The QUOTING axis counts too: a quote AROUND the target — opening, closing,
#    single or double — is stripped by the shell before `rm` ever sees the path,
#    so `rm -rf "/"` deletes exactly what `rm -rf /` deletes and the two must get
#    the same verdict. They did not: the rule accepted an opening quote and had
#    no ending for the closing one, so `"/"`, `'/'`, `"/usr"`, `"~"` and
#    `rm -rf build "/etc"` all returned 0. Worse than the hole was its SHAPE —
#    `rm -rf "~/"` did block, by accident (the home pattern's path-component
#    class swallowed the closing quote as if it were part of the path), so a
#    spot-check on the obvious spelling reported the axis as covered.
#    The rows below name one spelling each; the TARGET is what they vary:
#      rm -rf $VAR / "$VAR"        variable indirection (`PATH=/; rm -rf $PATH`)
#      rm -rf /   ·  rm -rf /*     the filesystem root
#      rm -rf ~   ·  ~/  ·  ~/Documents        HOME and its immediate children
#      rm -rf /Users/me  ·  /Users/me/Desktop  the same, spelled absolutely
#      rm -rf /usr  ·  /etc  ·  /var/folders   a system root or an immediate child
#      rm -rf /tmp  ·  /private/tmp            the scratch root itself, bare
#      rm -rf "/" · '/' · "/usr" · "~" · build "/etc"   any of the above QUOTED
#    NOT COVERED (deliberate, so everyday cleanup keeps working):
#      relative paths — `rm -rf node_modules`, `rm -rf ./dist`
#      anything INSIDE the scratch root — `rm -rf /tmp/navori-test-123`: a temp
#        dir is scratch by definition and agents create and delete them all day;
#        only wiping `/tmp` wholesale is the accident worth catching.
#      DEEP absolute paths — `rm -rf /Users/me/dev/app/node_modules`, `/tmp/x/y`:
#        past the first level under a root, a path is assumed to be project or
#        scratch data. Wiping HOME or a system dir is the accident worth
#        catching; a deep path is a targeted delete, and blocking every one of
#        them would fire daily (agents are told to use absolute paths) and only
#        teach the operator to route around the guard.
#      quoting SPLICED INTO the path, and backslash escapes — `rm -rf /"u"sr`,
#        `rm -rf "/us"r`, `rm -rf \~`, `rm -rf \/`. The shell removes those
#        before `rm` runs, so they name the same paths the rows above cover; the
#        guard reads TEXT and the pattern needs the path spelled contiguously.
#        This is the residue of the quoting axis, and it is named because the
#        row above claims that axis: quotes AROUND the target are covered,
#        quotes INSIDE it are not. Same class as the escaped-word limitation the
#        header already states (`b\ash f`), and it needs a deliberate hand —
#        nobody types `/"u"sr` by accident.
#      `sh -c`, `eval`, base64/printf obfuscation — seatbelt, not a sandbox.
#
#    FLAG NORMALIZATION (#509). The rule used to describe the danger by the
#    TEXT it usually wears (`-[a-zA-Z]*[rf]…`, lowercase) instead of by what
#    `rm` MEANS, so three everyday spellings of the same command walked past it:
#    `rm -R ~/` (POSIX/GNU/BSD all treat `-R` as `-r`), `rm --recursive --force
#    ~/`, and `rm -rf --no-preserve-root /` — the one command that erases the
#    system root, and the only one of the three that also evades the static
#    `deny` globs. So the flags are NORMALIZED before they are matched:
#      · long → short: `--recursive`→`-r`, `--force`→`-f`, `--dir`→`-d`.
#        Rewritten (not just alternated into the pattern) because a long flag
#        sits between `rm` and its target and otherwise breaks the run.
#      · `-R` ≡ `-r` lives in the character class instead: BSD `sed` has no
#        portable case-folding (`\l`/`\U` are GNU-only), and folding the whole
#        segment would corrupt the TARGET, which is case-sensitive.
#      · any other option token is allowed to sit anywhere in the run, so
#        `--no-preserve-root`, `--one-file-system` or a `--` separator no longer
#        detach the recursive flag from its target.
#    `segments_rm` is read by THIS rule only — rewriting `--force` globally
#    would otherwise reach the force-push rule.
#
#    EVERY OPERAND, NOT JUST THE FIRST. The same defect one axis over: the rule
#    matched `rm`, then the flags, then ONE target, so a harmless path in first
#    position detached the rule from everything after it — `rm -rf build /` and
#    `rm -rf node_modules ~/` both erased the root/HOME with exit 0. But `rm`
#    takes a LIST of operands and deletes every one of them, so sensitivity is a
#    property of the TARGET's shape (root / home / variable), never of its
#    position. `rm_arg` is therefore a run of ANY argument tokens — further
#    options and harmless operands alike — between the recursive flag and the
#    target, and the same run is allowed BEFORE the flag so that GNU's option
#    permutation (`rm build -rf /`, which really does erase `/` on Linux) is
#    covered too. False positives stay bounded because the verdict still hangs
#    on the target: `rm -rf build coverage` has no sensitive operand and keeps
#    passing, exactly as the verdict table demands.
#    `rm_arg` excludes `<`, `>` and `&` on purpose — what follows a redirection
#    or a `&` is not something `rm` deletes, so `rm -rf dist > /dev/null` (or
#    `rm dist & ls -R /usr`) must not be read as `rm -rf /dev/null`.
#
#    THE FALSE POSITIVE THIS BUYS, named rather than left to be discovered.
#    "Any token" also means tokens that are not operands of that `rm` at all, so
#    an UNQUOTED mention of `rm` anywhere in a segment now reaches forward to any
#    sensitive absolute path later in the SAME segment. Measured, all exit 2:
#      echo rm -rf build /usr
#      python3 -c "print(1)" # rm -rf a /bin/zsh      ← inside a comment
#      rm -rf "release /usr notes"                     ← one quoted operand
#    It is a deliberate trade, and a bounded one: the mention has to be
#    unquoted (a `-m "…rm -rf ~/…"` message or a heredoc body was already elided
#    into `live`, and `(^|[[:space:]])rm` does not match after a `"`), it has to
#    share a segment with the path (`;`, `&&`, `||`, `|` all end the reach), and
#    the path still has to be root/home/system — `echo rm -rf build dist` passes.
#    The everyday shapes that LOOK like this stay clean, and the verdict tables
#    pin them: `find … -exec rm -rf {} +`, `xargs rm -rf`, `rm -rf dist >
#    /dev/null`, `docker run --rm -v /var/run/docker.sock:…`, `tar -rf a.tar
#    /etc/hosts`, `cp -R /usr/share/x .`. Narrowing `rm_arg` to "options only"
#    is what reopens `rm -rf build /`, and an erased root costs more than a
#    blocked `echo`; the header's seatbelt framing is the standing answer, and
#    the way past a firing here is to quote the mention or split the segment.
segments_rm=$(printf '%s' "$segments" | sed -E \
  -e 's/(^|[[:space:]])--recursive([[:space:]]|$)/\1-r\2/g' \
  -e 's/(^|[[:space:]])--force([[:space:]]|$)/\1-f\2/g' \
  -e 's/(^|[[:space:]])--dir([[:space:]]|$)/\1-d\2/g')
#    `git rm --cached` is not a deletion (#655). It rewrites the INDEX and leaves
#    the file on disk — and it is the exact fix `doctor` prescribes for an
#    ephemeral that stayed tracked (#646), so the harness was blocking its own
#    advice the moment the path came from a variable. The `rm` VERB is renamed in
#    that ONE shape so `rm_run` stops seeing it; nothing else about the segment
#    changes.
#
#    Why not anchor `rm` to the start of the segment instead, which is the
#    tempting general fix: `xargs rm -rf /usr` and `find … -exec rm -rf {} +` put
#    the verb mid-segment and are genuinely destructive, so anchoring would let
#    them through. The verb has to stay reachable mid-segment; only this one
#    non-deleting spelling gets exempted.
#
#    It cannot be used to disarm a real deletion. The rewrite needs `git` before
#    the verb AND `--cached` in the SAME segment, and segments split on `;`,
#    `&&`, `||` and `|` — so a real recursive delete chained after a `git rm
#    --cached` still blocks on its own segment, and one that merely trails a
#    `--cached` token has no `git` and is untouched. Both are pinned in the
#    verdict table.
#
#    `_git_opt` lets git's own global options sit between the wrapper and the
#    verb, values included (`git -c k=v rm --cached`). That token run is the
#    widest part of the exemption and stays bounded by the three conditions
#    above: a segment beginning with `git` cannot hold a second command, and no
#    single `git` invocation deletes outside the repo.
_git_opt='-[^[:space:]]+[[:space:]]+([^-][^[:space:]]*[[:space:]]+)?'
segments_rm=$(printf '%s' "$segments_rm" | sed -E \
  -e "/--cached/ s/(^|[[:space:]])git([[:space:]]+(${_git_opt})*)rm([[:space:]])/\1git\2git-rm\4/g")
rm_arg='[^<>&[:space:]]+[[:space:]]+'           # any option OR operand token
rm_kill='-[a-zA-Z]*[rRf][a-zA-Z]*[[:space:]]+'  # a short option carrying r/R/f
rm_run="(^|[[:space:]])rm[[:space:]]+(${rm_arg})*${rm_kill}(${rm_arg})*"
rm_quote="[\"']?"                     # ONE optional quote, either flavour
rm_var='\$'                           # `$VAR`, `${VAR}` — any variable
rm_home='~(/[^[:space:]/]*)?|/(Users|home)(/[^[:space:]/]+(/[^[:space:]/]*)?)?'
rm_root='/\*?|/(Applications|Library|System|Volumes|bin|boot|dev|etc|lib|lib64|mnt|opt|root|sbin|srv|sys|usr|var)(/[^[:space:]/]*)?'
rm_tmp='/private(/tmp)?|/tmp'         # scratch root: the root itself, never a child
# The CLOSING quote is part of the ending, not an afterthought: without it the
# rule read `rm -rf "/"` as "root, then a character that is not the end of the
# segment" and returned 0. `rm_quote` appears on BOTH sides of the target below.
rm_end="/?${rm_quote}([[:space:]]|\$)"  # optional trailing `/`, closing quote, end
#    A VARIABLE target blocks only with a RECURSIVE flag (spec 0039 R23/R24): a
#    plain `rm -f "$TMPDIR/x"` deletes one file and is everyday cleanup, while
#    `rm -rf "$X"` can erase a tree. `rm_rec` is `rm_kill` narrowed to r/R (the
#    long `--recursive` was already rewritten to `-r`, combined `-rf`/`-fr` match
#    the class). Root, home and tmp keep the broader r/R/f flag run, unchanged.
rm_rec='-[a-zA-Z]*[rR][a-zA-Z]*[[:space:]]+'
rm_run_rec="(^|[[:space:]])rm[[:space:]]+(${rm_arg})*${rm_rec}(${rm_arg})*"
# GNU `rm` also accepts options AFTER the operands, so the recursive flag may
# follow the variable (`rm -f $X -r`, `rm $X -rf`). `--` is not special-cased:
# a `-r` token after it is treated as recursive too, the safe side (`rm -f --
# -r $X` blocks, as it did before).
rm_run_post="(^|[[:space:]])rm[[:space:]]+(${rm_arg})*${rm_quote}${rm_var}[^<>&[:space:]]*[[:space:]]+(${rm_arg})*-[a-zA-Z]*[rR][a-zA-Z]*([[:space:]]|\$)"
# Split in two (#1117) so each block carries the message it deserves: a root /
# home / system / scratch-root target has NO safe route; a variable target does.
if printf '%s' "$segments_rm" \
  | grep -qE "${rm_run}${rm_quote}((${rm_home}|${rm_root}|${rm_tmp})${rm_end})"; then
  block "recursive rm over root / home / system / scratch root" rm-root
fi
if printf '%s' "$segments_rm" \
  | grep -qE "${rm_run_rec}${rm_quote}${rm_var}" \
  || printf '%s' "$segments_rm" \
  | grep -qE "${rm_run_post}"; then
  block "recursive rm over a variable" rm-var \
    "the variable cannot be inspected; resolve it first and re-issue the delete as 'rm -rf <absolute path>' with the literal absolute path — the host then asks the user to confirm that exact command."
fi

# 3b. `--no-preserve-root` is an aggravating factor on its own (#509): it exists
#     for the single purpose of disarming the last safety net `rm` has, and no
#     legitimate use of it exists inside an agent. Target, flag order and
#     quoting are therefore irrelevant — its presence in an `rm` SEGMENT blocks.
#     "Quoting is irrelevant" is now true rather than asserted: the flag carries
#     the same `rm_quote` on both sides that rule 3's target does, so
#     `rm "--no-preserve-root" -rf ./build` blocks like the bare spelling. It
#     read as covered before and was not — the same shape as the target-side
#     hole, one rule over.
#     Scoped to the segment (grep is line-based) so an `rm` in one command and
#     the flag in another are never paired; a commit message or a heredoc body
#     that merely quotes it was already elided into `live` and never gets here.
if printf '%s' "$segments" \
  | grep -qE "(^|[[:space:]])rm[[:space:]](.*[[:space:]])?${rm_quote}--no-preserve-root${rm_quote}([[:space:]]|\$)"; then
  block "rm --no-preserve-root (disarms rm's own root protection)" no-preserve-root
fi

# 4. Fork bomb. Reads `live`, not `scan`: FIX C turns `(` into a space, which
#    would defuse the very pattern this rule looks for.
if printf '%s' "$live" | grep -qE ':\(\)[[:space:]]*\{[[:space:]]*:\|:'; then
  block "fork bomb" fork-bomb
fi

# 5. Writing to a raw block device (wipes a disk/partition).
if printf '%s' "$live" | grep -qE '(of=/dev/(sd|nvme|disk|hd)|>[[:space:]]*/dev/(sd|nvme|disk|hd))'; then
  block "direct write to a block device" block-device
fi

# 6. Shell rewrites of a file navori MAINTAINS (#530). In auto mode every edit
#    arrives as a shell command — `sed -i`, a heredoc, a `>` redirect — instead
#    of the `Edit` tool, and the two fail very differently: `Edit` aborts when
#    the old text doesn't match (a check that the agent understood the file),
#    while `sed -i` with a pattern that matches nothing exits 0 and a `>` with
#    the wrong path truncates the file. On a managed file the damage is the #523
#    shape: the body changes, its `hash=` no longer matches, navori marks the
#    block `user-modified` and STOPS UPDATING IT. Nothing announces that.
#
#    These files are a MIRROR, and the harness already says so in prose ("los
#    conflictos en `.claude/` y CLAUDE.md no se resuelven a mano: son espejo").
#    This rule is that policy made executable. The way to change them is to edit
#    the source asset and run `navori render --apply`, or `navori sync` to
#    reconcile — neither of which matches here, because neither redirects.
#
#    COVERED (blocked), by FORM of the write:
#      > path  ·  >| path        truncating redirect (`>>` append is NOT: it adds
#                                after the blocks and invalidates no hash)
#      sed -i … path             in-place rewrite
#      tee path                  overwrite (`tee -a` is an append, so it is not)
#    …and by TARGET, the marker-carrying outputs of `ENGINE_OUTPUTS`
#    (lib/health.ts), which is what "managed" means anywhere else in navori:
#      CLAUDE.md · AGENTS.md · .claude/settings.json
#      .claude/agents · .claude/skills · .claude/hooks
#      .agents/skills · .codex/config.toml · .codex/agents · .codex/hooks
#      .cursor/rules
#
#    NOT COVERED, and each exclusion is load-bearing:
#      .claude/progress/… and .codex/progress/…   the agent handoff files, for
#        BOTH engines. Every subagent ends by writing one, usually with a
#        heredoc; blocking that breaks the harness's own protocol with the
#        harness's own guard. They carry no markers, so nothing there can be
#        invalidated. Naming `.codex/` wholesale was exactly that bug: it
#        swallowed `.codex/progress/` and would have silenced every Codex
#        subagent's handoff (#389's rule caught it).
#      .claude/settings.local.json · .claude/worktrees/   machine-local, never
#        rendered, never marker-managed.
#      `python -c` writes, `awk > file`, `perl -i`. Copy/move/install/link
#        into exact render-owned paths are checked separately in rule 6d.
#        Enumerating write verbs is the losing half of this fight — the same
#        "describe the danger by its textual form" pattern the blind audit found
#        eight times. The PostToolUse watcher is the half that doesn't care about
#        form: it re-checks the hashes AFTER the fact, so anything that gets past
#        this rule still surfaces. This rule is the seatbelt; that one is the net.
managed_dir='\.claude/(agents|skills|hooks)|\.agents/skills|\.codex/(agents|hooks)|\.cursor/rules'
# Spec 0048 D4 (R3): in a Pi copy only, the exact names Navori writes under `.pi/`: its extension,
# manifest, hook copies and the role files of its roster. A `.pi/agents/<other>.md` is the user's.
# Empty everywhere else, so the Claude and Codex regex is the one it always was.
managed_pi=''
if [ "$nv_engine" = pi ]; then
  managed_pi='|\.pi/extensions/navori\.ts|\.pi/navori\.json|\.pi/navori/[^[:space:];&|]+|\.pi/agents/(scout|implementer|reviewer|scribe|auditor|architect|publisher)\.md'
fi
managed_path="(CLAUDE\.md|AGENTS\.md|\.claude/settings\.json|\.codex/config\.toml|(${managed_dir})/[^[:space:];&|]+${managed_pi})"
managed_rewrite_msg="shell rewrite of a navori-managed file — edit the source asset and run 'navori render --apply' (or 'navori sync'); a direct write invalidates the block hash and freezes it. If the target is outside this project (e.g. a scratchpad), write it with '>' or 'tee' and an absolute path instead"
# The redirect check reads `scan`, NOT `segments`: the split rewrites every `|`
# into a newline, so `>| CLAUDE.md` (forced clobber) would be torn in half and
# the target would land in a segment of its own. Reading the unsplit copy is
# safe HERE and nowhere else in this file, because the pattern is local — only
# whitespace may sit between the `>` and its target, so it cannot reach across a
# `&&` into another command the way rules 1-3 could.
# `-[a-zA-Z]*i[a-zA-Z]*[^[:space:]]*` accepts the backup-suffix spellings that
# are the everyday form on both platforms: GNU `sed -i.bak`, BSD `sed -i ''`.
# Missing them would have left the rule covering the tutorial spelling only.
# Case-INSENSITIVE (`-i`), same reasoning as the heredoc script-extension check
# above (~line 319): APFS is case-insensitive by default, so `> .CLAUDE/AGENTS/a.md`
# writes the same file as `.claude/agents/a.md` and must not slip past a
# case-sensitive match.
if printf '%s' "$scan" | grep -qiE "(^|[^>])>\|?[[:space:]]*(\./)?${managed_path}([[:space:]]|\$)" \
  || printf '%s' "$segments" | grep -qiE "(^|[[:space:]])sed[[:space:]]+(-[a-zA-Z]*i[a-zA-Z]*[^[:space:]]*|--in-place)([[:space:]]|=).*${managed_path}" \
  || printf '%s' "$segments" | grep -qiE "(^|[[:space:]])tee[[:space:]]+([^-][^[:space:]]*[[:space:]]+)*(\./)?${managed_path}([[:space:]]|\$)"; then
  block "$managed_rewrite_msg" managed-rewrite
fi

# 6b (#1034). The `>`/`>|`/`tee` arms above only ever match a BARE or
# `./`-relative managed path, by design — `sed -i`'s own arm is unanchored
# (`.*managed_path`) so it already catches an absolute target as a side effect,
# but `>`/`tee` never reach `managed_path` at all for an absolute one, in or out
# of the project (confirmed empirically, challenge_1027.md CONCERN 1). #1027
# proposed closing that by RESOLVING the target against the filesystem at
# check-time (`cd -P`, symlink checks) to decide "inside vs outside" — rejected
# (challenge_1027.md BLOCKER 1): an ordinary `rm <target> && ln -s <managed
# file> <target> && tee <target>` in the SAME command swaps what the literal
# path resolves to between the check and the write, so a filesystem check is
# TOCTOU-defeated by construction, not by an adversarial trick.
#
# What stays textual and TOCTOU-proof: matching an absolute target whose
# CHARACTERS start with this project's own path — no `cd`, no `pwd -P`, no
# `[ -L ]`, so there is nothing for a same-command `rm`/`ln -s` to invalidate.
# Two forms reach that:
#   - the RESOLVED value of $CLAUDE_PROJECT_DIR, regex-escaped so a literal
#     char in the path (this repo's own path has a space and a hyphen, "Dev -
#     Docs") is never read as a metacharacter;
#   - the UNRESOLVED variable text itself, `$CLAUDE_PROJECT_DIR` /
#     `${CLAUDE_PROJECT_DIR}`, which an agent can compose into a redirect
#     without ever expanding it (so this arm doesn't depend on the value).
# Quoted and unquoted forms both matter, and NOT just as "the whole target is
# quoted or it isn't": `"$CLAUDE_PROJECT_DIR"/CLAUDE.md` — quoting only the
# variable expansion, then continuing unquoted — is ordinary POSIX style a
# legitimate command uses unprompted, so the quote has to be optional AROUND
# THE PREFIX TOKEN ITSELF (both the literal value and the `$VAR`/`${VAR}` text),
# not only at the two ends of the whole match (#1034 round 2 review). A path
# with a space in it (like this repo's) also HAS to be quoted somewhere to be
# valid shell at all, so this isn't a cosmetic tolerance.
# Absolute paths OUTSIDE the project (any other prefix) stay allowed on
# purpose — the block message above offers exactly that escape (#1036), and a
# sibling directory that merely shares the prefix (`<proj>-otro/CLAUDE.md`)
# does not match either: the pattern requires a literal `/` (optionally
# quoted) right after the project path, and a sibling has `-otro/…` there
# instead.
# Without a project dir resolved, this arm is skipped entirely — same
# behavior as before #1034 — rather than matching against an empty prefix.
# Spec 0035 D2: `nv_project_dir` is `$CLAUDE_PROJECT_DIR` under Claude (same
# value, same guard as before) and the payload's `cwd` resolved to its git
# toplevel under Codex, so the SAME absolute-prefix protection now covers
# both engines instead of only firing when Claude's env var happens to be set.
if [ -n "${nv_project_dir:-}" ]; then
  # Strip a trailing slash before escaping: a trailing `/` would otherwise
  # need a doubled `//` to line up with `/${managed_path}` below and silently
  # stop matching (round 2 review, informational note 1).
  cpd_literal=$(printf '%s' "${nv_project_dir%/}" | sed -E 's#[^a-zA-Z0-9_/ -]#\\&#g')
  if [ "$nv_engine" = codex ]; then
    # The UNRESOLVED command substitution text itself — the exact form
    # `.codex/config.toml` uses for every hook command (build-config-toml.ts)
    # — which an agent can compose into a redirect without ever expanding it.
    unresolved_prefix='\$\(git rev-parse --show-toplevel\)'
  else
    unresolved_prefix='\$\{?CLAUDE_PROJECT_DIR\}?'
  fi
  abs_managed_path="[\"']?(${cpd_literal}|${unresolved_prefix})[\"']?/${managed_path}[\"']?"
  if printf '%s' "$scan" | grep -qiE "(^|[^>])>\|?[[:space:]]*${abs_managed_path}([[:space:]]|\$)" \
    || printf '%s' "$segments" | grep -qiE "(^|[[:space:]])tee[[:space:]]+([^-][^[:space:]]*[[:space:]]+)*${abs_managed_path}([[:space:]]|\$)"; then
    block "$managed_rewrite_msg" managed-rewrite
  fi
fi

# 6d. Copy/move/install/link protection uses exact render ownership, not the
# directory-wide legacy redirect rules. Keep Pi 6c below: copy-out from its
# control plane remains forbidden even when this destination-only lane allows.
# Exact render-owned copy/move destinations (spec 0053 R8). No filesystem discovery.
# Parse the live text separately: the legacy segment splitter also splits >& and
# removes parentheses from the trusted, literal git-toplevel prefix.
# One awk pass, bounded by the caller's CMD_MAX; no eval or shell word expansion.
# The awk runs byte-wise (LC_ALL=C): macOS awk aborts on a split multibyte char
# in `~` matching, and shell metacharacters and owned paths are ASCII anyway.
# A newline inside an open quote stays in the word (multi-line -m "$(cat <<EOF)");
# outside quotes it ends the segment; an unclosed quote at the end still fails.
# Heredoc bodies are NOT skipped here: the caller elides the inert ones (and their
# terminator) from the live text, and skipping on that text would hide commands.
# Paths are lexical against the tool cwd. Command-local directory changes,
# dynamic operands and arbitrary filesystem aliases are outside this seatbelt.
navori_copy_dest_safe() {
  LC_ALL=C NV_COPY_ROOT=${nv_project_dir:-} NV_COPY_CWD="$(payload_field cwd)" \
    NV_COPY_OWNED="$nv_owned_paths" awk '
  function slashes(p) { if (windows) gsub(/\\/, "/", p); return p }
  function norm(p, context,    n,a,i,k,out) {
    p = slashes(p)
    if (index(p, "${CLAUDE_PROJECT_DIR}") == 1)
      p = root substr(p, 22)
    else if (index(p, "$CLAUDE_PROJECT_DIR") == 1)
      p = root substr(p, 20)
    else if (index(p, "$(git rev-parse --show-toplevel)") == 1)
      p = root substr(p, 33)
    # Git Bash accepts drive-qualified paths; do not prepend cwd to them.
    if (p !~ /^([A-Za-z]:)?\//) p = (context == "" ? cwd : context) "/" p
    # Pi supplies the physical Git root on macOS, but tool cwd and operands
    # can retain /var or /tmp. Fold only these fixed aliases when the trusted
    # root is under /private; never inspect or expand arbitrary symlinks.
    if (root ~ /^\/private\/(var|tmp)(\/|$)/ && p ~ /^\/(var|tmp)(\/|$)/)
      p = "/private" p
    n = split(p, a, "/"); k = 0
    for (i = 1; i <= n; i++) {
      if (a[i] == "" || a[i] == ".") continue
      if (a[i] == "..") { if (k > 0) k--; continue }
      parts[++k] = a[i]
    }
    out = ""
    for (i = 1; i <= k; i++) out = out "/" parts[i]
    return tolower(out == "" ? "/" : out)
  }
  function owned(p, tree) {
    return (p in files) || (tree && (p in dirs))
  }
  function base(p,    a,n) {
    sub(/\/+$/, "", p); n = split(p, a, "/"); return a[n]
  }
  # Literal wrapper/global options only; unsupported copy contexts fail closed.
  function check(    i,v,argc,target,dir,recursive,noopts,x,s,d,j,move,wrapper,context,uncertain,k,c) {
    if (!nt) return
    i = 1; context = cwd
    while (i <= nt) {
      if (tok[i] ~ /^[A-Za-z_][A-Za-z0-9_]*=/) { i++; continue }
      wrapper = base(tok[i])
      if (wrapper != "command" && wrapper != "env" && wrapper != "nohup" && wrapper != "sudo") break
      i++
      while (i <= nt && tok[i] ~ /^-/) {
        x = tok[i++]
        if (x == "--") break
        if (wrapper == "command" && x == "-p") continue
        if (wrapper == "command" && (x == "-v" || x == "-V" || x == "--help")) return
        if (wrapper == "env" && (x == "-i" || x == "--ignore-environment")) continue
        if ((wrapper == "env" && (x == "-u" || x == "--unset")) || (wrapper == "sudo" && (x == "-u" || x == "-g"))) {
          if (i > nt) { bad = 1; return }
          i++; continue
        }
        if (wrapper == "env" && x ~ /^--unset=./) continue
        # Unknown wrapper options must not turn unrelated read-only commands
        # into managed-file rewrites. A recognizable copy still fails closed,
        # including a literal split-string argument such as env -S.
        for (j = i; j <= nt; j++)
          if (tok[j] ~ /(^|[ \t\/])(cp|mv|install|ln)([ \t]|$)/) { bad = 1; return }
        return
      }
    }
    v = base(tok[i]); i++
    if (v == "git") {
      uncertain = 0
      while (i <= nt && tok[i] ~ /^-/) {
        x = tok[i++]
        if (x == "--") break
        if (x == "--no-pager" || x == "--paginate" || x == "--literal-pathspecs") continue
        if (x == "-C") {
          if (i > nt) { bad = 1; return }
          if (tok[i] != "") context = norm(tok[i],context)
          i++; continue
        }
        if (x ~ /^-C./) { context = norm(substr(x,3),context); continue }
        if (x == "-c" || x == "--config-env" || x == "--git-dir" || x == "--work-tree" || x == "--namespace" || x == "--super-prefix") {
          if (i > nt) { bad = 1; return }
          i++; uncertain = 1; continue
        }
        # Config/work-tree/pathspec options may change operand interpretation.
        # Never discover their effects from the filesystem or execute Git.
        uncertain = 1
      }
      if (uncertain) {
        if (tok[i] == "mv") bad = 1
        return
      }
      if (tok[i] != "mv") return
      v = "mv"; i++
    }
    if (v != "cp" && v != "mv" && v != "install" && v != "ln") return
    move = (v == "mv"); argc = 0; target = ""; recursive = 0; noopts = 0
    for (; i <= nt; i++) {
      x = tok[i]
      if (!noopts && x == "--") { noopts = 1; continue }
      if (!noopts && (x == "--help" || x == "--version")) return
      if (!noopts && (x == "-t" || x == "--target-directory")) {
        if (++i > nt) { bad = 1; return }
        target = tok[i]; continue
      }
      if (!noopts && x ~ /^--target-directory=/) { target = substr(x,20); continue }
      if (!noopts && x ~ /^-t./) { target = substr(x,3); continue }
      if (!noopts && v == "install" && (x == "-m" || x == "-o" || x == "-g" || x == "--mode" || x == "--owner" || x == "--group")) {
        if (++i > nt) { bad = 1; return }; continue
      }
      if (!noopts && x ~ /^-/) {
        if (x ~ /^--(mode|owner|group)=/ || x ~ /^-[mog].+/ && v == "install") continue
        if (x ~ /^-[A-Za-z]/ && x !~ /^--/) {
          # Walk flags in order: t consumes the cluster remainder or next word.
          # Unknown/operand-taking flags cannot silently eat a source or target.
          for (k = 2; k <= length(x); k++) {
            c = substr(x,k,1)
            if (c == "t") {
              target = substr(x,k+1)
              if (target == "") {
                if (++i > nt) { bad = 1; return }
                target = tok[i]
              }
              break
            }
            if (c !~ /^[fivnsrRaPTdHLPpuvx]$/) { bad = 1; return }
            if (c ~ /^[rRa]$/) recursive = 1
          }
          continue
        }
        if (x ~ /^--(force|recursive|archive|no-target-directory|symbolic|verbose|remove-destination|preserve|no-clobber)$/) {
          if (x == "--recursive" || x == "--archive") recursive = 1
          continue
        }
        bad = 1; return
      }
      args[++argc] = x
    }
    if (target == "") {
      if (argc < 2) return
      target = args[argc--]
      dir = (target ~ /\/$/ || argc > 1)
    } else dir = 1
    d = norm(target,context)
    if (owned(d,0)) { bad = 1; return }
    # A directory is inferred only from exact owned descendants, not a glob.
    if (owned(d,1)) dir = 1
    for (j = 1; j <= argc; j++) {
      s = norm(args[j],context)
      if (move && owned(s,1)) { bad = 1; return }
      if (dir && owned(norm(target "/" base(args[j]),context),1)) { bad = 1; return }
      # Contents of a recursive external tree are unknown without FS discovery.
      if (recursive && owned(d,1)) { bad = 1; return }
    }
  }
  function word() { if (have) tok[++nt] = buf; buf = ""; have = 0 }
  function segment() { word(); check(); nt = 0 }
  BEGIN {
    root = ENVIRON["NV_COPY_ROOT"]
    if (root == "") root = ENVIRON["PWD"]
    # Backslashes are separators only for Windows roots; on Unix they may
    # be literal filename characters inside shell quotes.
    windows = (root ~ /^[A-Za-z]:/ || substr(root,1,2) == "\\\\")
    root = slashes(root); cwd = slashes(ENVIRON["NV_COPY_CWD"])
    # Use the same conservative spelling when Claude supplies the lexical root.
    if (root ~ /^\/(var|tmp)(\/|$)/) root = "/private" root
    if (cwd == "") cwd = root
    count = split(ENVIRON["NV_COPY_OWNED"], paths, "\n")
    for (z = 1; z <= count; z++) {
      p = norm(root "/" paths[z]); files[p] = 1
      # Ancestors come only from the trusted exact inventory, never a glob.
      while (p != "/") {
        sub(/\/[^\/]*$/, "", p)
        if (p == "") p = "/"
        dirs[p] = 1
      }
    }
  }
  {
    line = $0
    for (pos = 1; pos <= length(line); pos++) {
      c = substr(line,pos,1)
      if (escape) { buf = buf c; have = 1; escape = 0; continue }
      if (c == "\\" && quote != "\047") {
        # Within double quotes, Bash retains backslashes before ordinary
        # characters (including drive-path components such as C:\repo).
        if (quote == "\042" && pos < length(line) && substr(line,pos+1,1) !~ /[$`"\\]/) {
          buf = buf c; have = 1; continue
        }
        escape = 1; continue
      }
      if (quote != "") {
        if (c == quote) quote = ""
        else buf = buf c
        have = 1; continue
      }
      if (c == "\047" || c == "\042") { quote = c; have = 1; continue }
      if (substr(line,pos,21) == "${CLAUDE_PROJECT_DIR}") {
        buf = buf substr(line,pos,21); have = 1; pos += 20; continue
      }
      # Preserve the one supported literal substitution, without executing it.
      if (substr(line,pos,32) == "$(git rev-parse --show-toplevel)") {
        buf = buf substr(line,pos,32); have = 1; pos += 31; continue
      }
      if (c == "#" && !have) break
      if (c == ">" || c == "<" || (c == "&" && substr(line,pos+1,1) == ">")) {
        if (have && buf ~ /^[0-9]+$/) { buf = ""; have = 0 } else word()
        # Redirection operators and their single quoted/unquoted operand.
        while (substr(line,pos,1) ~ /[<>&|]/ && pos <= length(line)) pos++
        while (substr(line,pos,1) ~ /[ \t]/ && pos <= length(line)) pos++
        rq = ""
        for (; pos <= length(line); pos++) {
          rc = substr(line,pos,1)
          if (rq != "") { if (rc == rq) rq = ""; continue }
          if (rc == "\047" || rc == "\042") { rq = rc; continue }
          if (rc ~ /[ \t;&|]/) break
        }
        if (rq != "") bad = 1
        pos--; continue
      }
      if (c ~ /[;&|(){}]/) { segment(); continue }
      if (c ~ /[ \t]/) { word(); continue }
      buf = buf c; have = 1
    }
    if (escape) escape = 0
    else if (quote != "") { buf = buf "\n"; have = 1 }
    else segment()
  }
  END { if (quote != "" || escape) bad = 1; segment(); exit (bad ? 2 : 0) }
  ' <<EOF
$live
EOF
}
