  fi
  navori_inert_skeleton
  navori_inert_live
  navori_inert_segments
  # `&` operator over the live text: newlines flattened and quoted spans dropped
  # (a quote may span lines), then a lone `&` — not adjacent to `&`, `>`, `<`,
  # `|` or an escaping backslash. `2>&1`, `&>`, `|&`, `&&` all have such a
  # neighbour; a trailing `&` and `a & b` do not.
  _flat=$(printf '%s' "$live" | tr '\n' ' ' | sed -E -e "s/'[^']*'//g" -e 's/"[^"]*"//g')
  if printf '%s' "$_flat" | grep -qE '(^|[^&>|<\\])&([^&>]|$)'; then
    block "operador de shell & (segundo plano) dentro de un subagente"
  fi
  # nohup / setsid / disown as the command of a segment, behind the simple
  # prefixes that keep it the command (`sudo`, `env`, `time`, `command`, `exec`).
  if printf '%s' "$segments" | grep -qE '^[[:space:]]*(((sudo|env|time|command|exec)[[:space:]]+)+)?(nohup|setsid|disown)([[:space:]]|$)'; then
    block "nohup/setsid/disown dentro de un subagente"
  fi
fi

navori_audit_verdict="allow"
navori_audit_reason="no backgrounded"
exit 0
