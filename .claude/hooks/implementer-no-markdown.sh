fi
if printf '%s' "$cmd" | grep -qiE "(^|[;&|[:space:]])perl[[:space:]]+-[a-zA-Z]*i[a-zA-Z]*[^[:space:]]*([[:space:]]|=).*${MD_EXT}([[:space:]]|;|&|\\||\$)"; then
  block "'perl -i' sobre un archivo .md/.mdx"
fi

# 4. `cp`/`mv` onto a `.md`/`.mdx` target — the atomic-write idiom (write a
# temp file, then move it onto the managed path). Anchored on the LAST operand
# of the invocation (greedy `.*` before the final `[[:space:]]`), since that is
# where `cp`/`mv` read their destination.
if printf '%s' "$cmd" | grep -qiE "(^|[;&|[:space:]])(cp|mv)[[:space:]]+.*[[:space:]][^[:space:];&|]*${MD_EXT}([[:space:]]|;|&|\\||\$)"; then
  block "'cp'/'mv' hacia un archivo .md/.mdx"
fi

# 5. Interpreter writes (#1129). Inspect text only: never execute supplied
# code. Flatten heredocs so an open() mode can appear on a separate line.
# Require all three clues: interpreter invocation, literal Markdown path, and
# write API/mode. Read APIs and stdout writes alone must not trigger this rule.
interpreter_cmd=$(printf '%s' "$cmd" | tr '\n' ' ')
INTERPRETER='(^|[;&|[:space:]])([^[:space:];&|]*/)?(python([0-9]+(\.[0-9]+)*)?|node|ruby|perl|deno|bun)([[:space:]]|$)'
MD_LITERAL="${MD_EXT}(['\"]|[[:space:]]|$)"
WRITE_API='(^|[^[:alnum:]_])(writeFile(Sync)?|appendFile(Sync)?|writeTextFile(Sync)?|write_text|write_bytes|copyFile(Sync)?|cpSync|renameSync)[[:space:]]*\(|shutil[[:space:]]*\.[[:space:]]*(copy|copy2|copyfile|copyfileobj|copytree|move)[[:space:]]*\(|os[[:space:]]*\.[[:space:]]*(rename|renames|replace)[[:space:]]*\(|\.[[:space:]]*(rename|replace)[[:space:]]*\([^,()]*\)'
FILE_WRITE='(File|Bun)[[:space:]]*\.[[:space:]]*(write|binwrite)[[:space:]]*\('
OPEN_WRITE="(^|[^[:alnum:]_])open[[:space:]]*\\([^)]*,[[:space:]]*(mode[[:space:]]*=[[:space:]]*)?['\"]([wax][bt+]*|r[bt]*\\+|[+]?>>?)['\"]"
if printf '%s' "$interpreter_cmd" | grep -qE "$INTERPRETER" &&
  printf '%s' "$interpreter_cmd" | grep -qiE "$MD_LITERAL" &&
  printf '%s' "$interpreter_cmd" | grep -qE "${WRITE_API}|${FILE_WRITE}|${OPEN_WRITE}"; then
  # The program is fixed hook code. The submitted command enters only on
  # stdin as data; never eval it. A nonzero analyzer, missing node, empty or
  # malformed output all fall through to the existing exit-2 block.
  IFS= read -r -d '' navori_json_analyzer <<'NAVORI_JSON_ANALYZER' || :
const input = require("node:fs").readFileSync(0, "utf8");
const fail = () => { throw Error("unrecognized metadata program"); };
try {
  if (Buffer.byteLength(input) > 16384) fail();
  const shell = /^[ \t]*node[ \t]+-e[ \t]+\x27([^\x27]*)\x27[ \t]*$/s.exec(input);
  if (!shell) fail();
