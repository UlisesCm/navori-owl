# Case-insensitive `.md`/`.mdx`: macOS ships a case-insensitive filesystem, so
# `NOTES.MD` writes the same file `notes.md` does.
is_md_path() {
  case "$1" in
    *.[mM][dD] | *.[mM][dD][xX]) return 0 ;;
    *) return 1 ;;
  esac
}

# True when $1 is relative to a doctrine prefix (closed list, exact match or a
# non-empty remainder under a directory prefix).
nv_rel_is_doctrine() {
  local rel=$1 prefix
  for prefix in "${navori_doctrine_prefixes[@]}"; do
    case "$prefix" in
      */) case "$rel" in "$prefix"?*) return 0 ;; esac ;;
      *) [ "$rel" = "$prefix" ] && return 0 ;;
    esac
  done
  return 1
}

# Absolute $1 inside ANOTHER registered worktree of the session's repo (#1330).
# Same identity primitives as #1329's review-edit-binding (physical path with no
# symlink component, registered in `git worktree list`, same --git-common-dir),
# fail closed on any doubt. Prints the path relative to that worktree's toplevel.
# Residual ceiling (documented): every registered worktree of the repo is trusted
# for the doctrine prefixes; no per-delivery grant exists before review begins.
nv_sibling_rel() {
  local p=$1 cursor="" part dir top session common sessioncommon rest list
  case "$p" in /*) ;; *) return 1 ;; esac
  # No symlink in any existing component, leaf included.
  rest=${p#/}
  while [ -n "$rest" ]; do
    part=${rest%%/*}
    if [ "$part" = "$rest" ]; then rest=""; else rest=${rest#*/}; fi
    cursor="$cursor/$part"
    if [ -L "$cursor" ]; then return 1; fi
  done
  dir=${p%/*}
  while [ -n "$dir" ] && [ ! -d "$dir" ]; do dir=${dir%/*}; done
  [ -n "$dir" ] || return 1
  top=$(git -c core.fsmonitor=false -C "$dir" rev-parse --show-toplevel 2>/dev/null) || return 1
  [ -n "$top" ] || return 1
  case "$p" in "$top"/?*) ;; *) return 1 ;; esac
  common=$(git -c core.fsmonitor=false -C "$top" rev-parse --path-format=absolute --git-common-dir 2>/dev/null) || return 1
  [ -n "$common" ] || return 1
  for session in "${nv_project_dir:-}" "$(git -C "$(payload_field cwd)" rev-parse --show-toplevel 2>/dev/null || true)"; do
    [ -n "$session" ] || continue
    sessioncommon=$(git -c core.fsmonitor=false -C "$session" rev-parse --path-format=absolute --git-common-dir 2>/dev/null) || continue
    [ "$sessioncommon" = "$common" ] || continue
    list=$(git -c core.fsmonitor=false -C "$session" worktree list --porcelain 2>/dev/null) || continue
    if printf '%s\n' "$list" | grep -Fxq "worktree $top" &&
      printf '%s\n' "$list" | grep -Fxq "worktree ${session%/}"; then
      printf '%s' "${p#"$top"/}"
      return 0
    fi
  done
  return 1
}

# True when $1 (a `.md`/`.mdx` target of an EDIT tool) is AI doctrine: relative to
# the repo root, or absolute and inside it or inside another registered worktree
# of the same repo (#1330); never with a `..` segment. Cheap roots first.
is_doctrine_path() {
  local p=$1 rel root candidate
  case "$p" in
    .. | ../* | */.. | */../*) return 1 ;;
  esac
  case "$p" in
    /*)
      rel=""
      for candidate in "${nv_project_dir:-}" "$(git -C "$(payload_field cwd)" rev-parse --show-toplevel 2>/dev/null || true)"; do
        root=${candidate%/}
        [ -n "$root" ] || continue
        case "$p" in
          "$root"/*) rel=${p#"$root"/}; break ;;
        esac
      done
      if [ -n "$rel" ] && nv_rel_is_doctrine "$rel"; then return 0; fi
      rel=$(nv_sibling_rel "$p") || return 1
      [ -n "$rel" ] || return 1
      ;;
    *) rel=${p#./} ;;
  esac
  nv_rel_is_doctrine "$rel"
}

